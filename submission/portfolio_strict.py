        '    `cx(a,b) rz(t) b cx(a,b)` equals `cx(b,a) rz(t) a cx(b,a)`. Orienting each block so that the\n'
        "    endpoint with the larger interaction degree is the control leaves the hub's wire almost free of\n"
        '    single-qubit gates within a `cz` layer, so the hub can stay parked in the entangling zone.\n'
        '    """\n'
        '    index = {bit: i for i, bit in enumerate(circuit.qubits)}\n'
        '    data = list(circuit.data)\n'
        '    degree: dict[int, int] = defaultdict(int)\n'
        '    seen = set()\n'
        '    for instruction in data:\n'
        '        if len(instruction.qubits) == 2:\n'
        '            a, b = sorted(index[q] for q in instruction.qubits)\n'
        '            if (a, b) not in seen:\n'
        '                seen.add((a, b))\n'
        '                degree[a] += 1\n'
        '                degree[b] += 1\n'
        '    nxt: dict[tuple[int, int], int] = {}\n'
        '    last: dict[int, int] = {}\n'
        '    for i in range(len(data) - 1, -1, -1):\n'
        '        for qubit in data[i].qubits:\n'
        '            q = index[qubit]\n'
        '            nxt[(i, q)] = last.get(q)\n'
        '            last[q] = i\n'
        '    out = circuit.copy_empty_like()\n'
        '    skip = set()\n'
        '    for i, instruction in enumerate(data):\n'
        '        if i in skip:\n'
        '            continue\n'
        '        if instruction.operation.name == "cx":\n'
        '            a, b = (index[q] for q in instruction.qubits)\n'
        '            j = nxt.get((i, b))\n'
        '            if j is not None and data[j].operation.name == "rz" and index[data[j].qubits[0]] == b:\n'
        '                k = nxt.get((j, b))\n'
        '                if (\n'
        '                    k is not None\n'
        '                    and k == nxt.get((i, a))\n'
        '                    and data[k].operation.name == "cx"\n'
        '                    and [index[q] for q in data[k].qubits] == [a, b]\n'
        '                ):\n'
        '                    angle = data[j].operation.params[0]\n'
        '                    skip |= {j, k}\n'
        '                    if degree[b] > degree[a]:\n'
        '                        a, b = b, a\n'
        '                    out.cx(a, b)\n'
        '                    out.rz(angle, b)\n'
        '                    out.cx(a, b)\n'
        '                    continue\n'
        '        out.append(instruction)\n'
        '    return out\n'
        '\n'
        '\n'
        'def _native_key(native: QuantumCircuit):\n'
        '    """Cheap structural signature, used to skip a candidate whose native circuit is identical."""\n'
        '    return tuple((instruction.operation.name, tuple(instruction.qubits), instruction.operation.params)\n'
        '                 for instruction in native.data)\n'
        '\n'
        '\n'
        '# ------------------------------------------------------------------ 2. round scheduling\n'
        '\n'
        '\n'
        '@dataclass\n'
        'class Phase:\n'
        '    """One round: 1q/measure `ops`, then one `cz` per entry of `pairs` (all pairs disjoint)."""\n'
        '\n'
        '    ops: list[Any] = field(default_factory=list)\n'
        '    pairs: list[Any] = field(default_factory=list)\n'
        '\n'
        '\n'
        'def schedule_rounds(native: QuantumCircuit) -> list[Phase]:\n'
        '    """ASAP layering of the per-qubit dependency DAG into rounds of a greedy maximal `cz` matching."""\n'
        '    index = {bit: i for i, bit in enumerate(native.qubits)}\n'
        '    cindex = {bit: i for i, bit in enumerate(native.clbits)}\n'
        '    items = []\n'
        '    for instruction in native.data:\n'
        '        items.append(\n'
        '            (\n'
        '                instruction.operation,\n'
        '                [index[q] for q in instruction.qubits],\n'
        '                [cindex[c] for c in instruction.clbits],\n'
        '            )\n'
        '        )\n'
        '    total = len(items)\n'
        '    if total == 0:\n'
        '        return []\n'
        '    nq = len(index)\n'
        '    fifo: list[list[int]] = [[] for _ in range(nq)]\n'
        '    for i, (_, qargs, _) in enumerate(items):\n'
        '        for q in qargs:\n'
        '            fifo[q].append(i)\n'
        '    ptr = [0] * nq\n'
        '    wait = [0] * total\n'
        '    for i, (_, qargs, _) in enumerate(items):\n'
        '        wait[i] = sum(1 for q in qargs if fifo[q][0] != i)\n'
        '    is_cz = [op.name == "cz" for op, _, _ in items]\n'
        '    done = [False] * total\n'
        '    ready1 = [i for i in range(total) if wait[i] == 0 and not is_cz[i]]\n'
        '    ready2 = [i for i in range(total) if wait[i] == 0 and is_cz[i]]\n'
        '    heapq.heapify(ready1)\n'
        '    heapq.heapify(ready2)\n'
        '    remaining = total\n'
        '    phases: list[Phase] = []\n'
        '\n'
        '    def advance(i: int) -> None:\n'
        '        for q in items[i][1]:\n'
        '            ptr[q] += 1\n'
        '            if ptr[q] < len(fifo[q]):\n'
        '                j = fifo[q][ptr[q]]\n'
        '                if wait[j] > 0:\n'
        '                    wait[j] -= 1\n'
        '                    if wait[j] == 0:\n'
        '                        heapq.heappush(ready2 if is_cz[j] else ready1, j)\n'
        '\n'
        '    while remaining > 0:\n'
        '        phase = Phase()\n'
        '        # (a) every ready 1q gate / measure\n'
        '        while ready1:\n'
        '            i = heapq.heappop(ready1)\n'
        '            if done[i] or wait[i] != 0:\n'
        '                continue\n'
        '            done[i] = True\n'
        '            remaining -= 1\n'
        '            phase.ops.append(i)\n'
        '            advance(i)\n'
        '        # (b) greedy maximal matching of the ready cz gates\n'
        '        cands = []\n'
        '        while ready2:\n'
        '            i = heapq.heappop(ready2)\n'
        '            if done[i] or wait[i] != 0:\n'
        '                continue\n'
        '            cands.append(i)\n'
        '        used: set[int] = set()\n'
        '        accepted = []\n'
        '        for i in cands:\n'
        '            u, v = items[i][1]\n'
        '            if u in used or v in used:\n'
        '                continue\n'
        '            used.add(u)\n'
        '            used.add(v)\n'
        '            accepted.append(i)\n'
        '        chosen = set(accepted)\n'
        '        for i in cands:\n'
        '            if i not in chosen:\n'
        '                heapq.heappush(ready2, i)\n'
        '        for i in accepted:\n'
        '            done[i] = True\n'
        '            remaining -= 1\n'
        '            phase.pairs.append((items[i][1][0], items[i][1][1], i))\n'
        '            advance(i)\n'
        '        if not phase.ops and not phase.pairs:\n'
        '            raise AssertionError("stalled scheduler: no ready instruction in a DAG")\n'
        '        phases.append(phase)\n'
        '\n'
        '    for phase in phases:\n'
        '        phase.ops = [items[i] for i in phase.ops]\n'
        '        phase.pairs = [(u, v, items[i][0]) for (u, v, i) in phase.pairs]\n'
        '    return phases\n'
        '\n'
        '\n'
        '# ------------------------------------------------------------------ 5a. legal move builder\n'
        '\n'
        '\n'
        'def move_params(atoms: dict[int, tuple[Site, Site]], occupant: dict[Site, int]):\n'
        '    """The validator\'s move rules, re-implemented. `atoms`: qubit -> (source site, target site)."""\n'
        '    if not atoms:\n'
        '        return None\n'
        '    row_map: dict[int, int] = {}\n'
        '    col_map: dict[int, int] = {}\n'
        '    src_zone = set()\n'
        '    dst_zone = set()\n'
        '    for src, dst in atoms.values():\n'
        '        sx, sy = src\n'
        '        dx, dy = dst\n'
        '        if not (0 <= sx <= 9 and 0 <= dx <= 9):\n'
        '            return None\n'
        '        if sy in row_map and row_map[sy] != dy:\n'
        '            return None\n'
        '        if sx in col_map and col_map[sx] != dx:\n'
        '            return None\n'
        '        row_map[sy] = dy\n'
        '        col_map[sx] = dx\n'
        '        src_zone.add(sy >= ENT_Y0)\n'
        '        dst_zone.add(dy >= ENT_Y0)\n'
        '    if len(src_zone) != 1 or len(dst_zone) != 1:\n'
        '        return None\n'
        '    src_rows = sorted(row_map)\n'
        '    src_cols = sorted(col_map)\n'
        '    if any(row_map[b] <= row_map[a] for a, b in itertools.pairwise(src_rows)):\n'
        '        return None\n'
        '    if any(col_map[b] <= col_map[a] for a, b in itertools.pairwise(src_cols)):\n'
        '        return None\n'
        '    rows = tuple(range(src_rows[0], src_rows[-1] + 1))\n'
        '    cols = tuple(range(src_cols[0], src_cols[-1] + 1))\n'
        '    y_lo, y_hi = rows[0], rows[-1]\n'
        '    x_lo, x_hi = cols[0], cols[-1]\n'
        '    for (x, y), q in occupant.items():\n'
        '        if x_lo <= x <= x_hi and y_lo <= y <= y_hi and q not in atoms:\n'
        '            return None\n'
        '    for dst in (v[1] for v in atoms.values()):\n'
        '        other = occupant.get(dst)\n'
        '        if other is not None and other not in atoms:\n'
        '            return None\n'
        '    new_rows = tuple(row_map[y] for y in src_rows)\n'
        '    new_cols = tuple(col_map[x] for x in src_cols)\n'
        '    if len(new_rows) > len(rows) or len(new_cols) > len(cols):\n'
        '        return None\n'
        '    return rows, cols, new_rows, new_cols\n'
        '\n'
        '\n'
        'def move_cost(atoms: dict[int, tuple[Site, Site]]) -> float:\n'
        '    """Scored cost of a move: the longest physical distance travelled by one of its atoms."""\n'
        '    best = 0.0\n'
        '    for src, dst in atoms.values():\n'
        '        d = math.dist(_physical(src), _physical(dst))\n'
        '        if d > best:\n'
        '            best = d\n'
        '    return best\n'
        '\n'
        '\n'
        '# ------------------------------------------------------------------ 3. target assignment\n'
        '\n'
        '\n'
        'def _host_row_of(u, v, pos):\n'
        '    yu, yv = pos[u][1], pos[v][1]\n'
        '    return yu if yu <= yv else yv\n'
        '\n'
        '\n'
        'def assign_targets(pairs, pos: dict[int, Site], strategy: str = "compact"):\n'
        '    """Give every round pair an entangling interaction pair.\n'
        '\n'
        '    Returns `(targets, visitors, assigned, overflow)`: `targets` maps qubit -> entangling site,\n'
        '    `visitors` is the set of atoms that travel from another storage row, `assigned` the pairs that\n'
        '    got a site and `overflow` the (never expected) pairs that would need an 11th entangling row.\n'
        '    The atom of a cross-row pair in the smaller row is the host and sits on the even site.\n'
        '\n'
        '    `compact` gives host row `y` the entangling row `10 + rank(y)` (monotone, so multi-row\n'
        '    rectangles can merge); `flat` fills the lowest entangling rows slot by slot, which minimises the\n'
        '    vertical travel when the atoms cannot merge anyway.\n'
        '    """\n'
        '    row_pairs: dict[int, list[Any]] = defaultdict(list)\n'
        '    for pair in pairs:\n'
        '        row_pairs[_host_row_of(pair[0], pair[1], pos)].append(pair)\n'
        '    host_rows = sorted(row_pairs)\n'
        '    by_column = {}\n'
        '    for y in host_rows:\n'
        '        by_column[y] = sorted(row_pairs[y], key=lambda pair: pos[pair[0]][0] if pos[pair[0]][1] == y else pos[pair[1]][0])\n'
        '\n'
        '    groups = []  # (host row, chunk of <= 5 pairs, candidate slot lines, target entangling row)\n'
        '    used_rows: set[int] = set()\n'
        '    overflow: list[Any] = []\n'
        '    if strategy == "flat":\n'
        '        row = ENT_Y0\n'
        '        taken = 0\n'
        '        for y in host_rows:\n'
        '            hosted = by_column[y]\n'
        '            index = 0\n'
        '            while index < len(hosted):\n'
        '                if taken >= N_PAIRS_PER_ROW:\n'
        '                    row += 1\n'
        '                    taken = 0\n'
        '                if row > ENTANGLING[3]:\n'
        '                    overflow.extend(hosted[index:])\n'
        '                    break\n'
        '                capacity = N_PAIRS_PER_ROW - taken\n'
        '                chunk = hosted[index : index + capacity]\n'
        '                groups.append((y, chunk, tuple(range(taken, taken + len(chunk))), row))\n'
        '                taken += len(chunk)\n'
        '                index += len(chunk)\n'
        '        extra = []\n'
        '    else:\n'
        '        target_of = {y: ENT_Y0 + i for i, y in enumerate(host_rows)}\n'
        '        extra = []\n'
        '        for y in host_rows:\n'
        '            hosted = by_column[y]\n'
        '            row = target_of[y]\n'
        '            groups.append((y, hosted[:N_PAIRS_PER_ROW], tuple(range(N_PAIRS_PER_ROW)), row))\n'
        '            used_rows.add(row)\n'
        '            if len(hosted) > N_PAIRS_PER_ROW:\n'
        '                extra.append((y, hosted[N_PAIRS_PER_ROW:], row))\n'
        '        for y, rest, first_row in extra:\n'
        '            for start in range(0, len(rest), N_PAIRS_PER_ROW):\n'
        '                chunk = rest[start : start + N_PAIRS_PER_ROW]\n'
        '                row = None\n'
        '                for candidate in itertools.chain(range(first_row + 1, ENTANGLING[3] + 1), range(ENT_Y0, first_row + 1)):\n'
        '                    if candidate not in used_rows:\n'
        '                        row = candidate\n'
        '                        break\n'
        '                if row is None:\n'
        '                    overflow.extend(chunk)\n'
        '                    continue\n'
        '                used_rows.add(row)\n'
        '                groups.append((y, chunk, tuple(range(N_PAIRS_PER_ROW)), row))\n'
        '\n'
        '    targets: dict[int, Site] = {}\n'
        '    visitors: set[int] = set()\n'
        '    assigned = []\n'
        '    for y, chunk, slots, row in groups:\n'
        '        if not chunk:\n'
        '            continue\n'
        '        host_costs = []\n'
        '        visit_costs = []\n'
        '        for pair in chunk:\n'
        '            u, v = pair[0], pair[1]\n'
        '            if pos[u][1] == pos[v][1]:\n'
        '                a, b = (u, v) if pos[u][0] <= pos[v][0] else (v, u)\n'
        '                hc = []\n'
        '                vc = []\n'
        '                for k in slots:\n'
        '                    hc.append(\n'
        '                        max(\n'
        '                            math.dist(_physical((2 * k, row)), _physical(pos[a])),\n'
        '                            math.dist(_physical((2 * k + 1, row)), _physical(pos[b])),\n'
        '                        )\n'
        '                    )\n'
        '                    vc.append(0.0)\n'
        '            else:\n'
        '                host, visitor = (u, v) if pos[u][1] == y else (v, u)\n'
        '                hc = [math.dist(_physical((2 * k, row)), _physical(pos[host])) for k in slots]\n'
        '                vc = [math.dist(_physical((2 * k + 1, row)), _physical(pos[visitor])) for k in slots]\n'
        '            host_costs.append(hc)\n'
        '            visit_costs.append(vc)\n'
        '\n'
        '        best_score = None\n'
        '        best_combo = None\n'
        '        m = len(chunk)\n'
        '        if m == len(slots):\n'
        '            best_combo = tuple(range(m))\n'
        '        else:\n'
        '            for combo in itertools.combinations(range(len(slots)), m):\n'
        '                host_max = 0.0\n'
        '                visit_sum = 0.0\n'
        '                for idx, slot in enumerate(combo):\n'
        '                    value = host_costs[idx][slot]\n'
        '                    if value > host_max:\n'
        '                        host_max = value\n'
        '                    visit_sum += visit_costs[idx][slot]\n'
        '                score = host_max + visit_sum\n'
        '                if best_score is None or score < best_score:\n'
        '                    best_score = score\n'
        '                    best_combo = combo\n'
        '        for idx, slot_index in enumerate(best_combo):\n'
        '            k = slots[slot_index]\n'
        '            u, v = chunk[idx][0], chunk[idx][1]\n'
        '            if pos[u][1] == pos[v][1]:\n'
        '                a, b = (u, v) if pos[u][0] <= pos[v][0] else (v, u)\n'
        '            else:\n'
        '                host, visitor = (u, v) if pos[u][1] == y else (v, u)\n'
        '                a, b = host, visitor\n'
        '                visitors.add(visitor)\n'
        '            targets[a] = (2 * k, row)\n'
        '            targets[b] = (2 * k + 1, row)\n'
        '            assigned.append(chunk[idx])\n'
        '    return targets, visitors, assigned, overflow\n'
        '\n'
        '\n'
        '# ------------------------------------------------------------------ 4. move planning\n'
        '\n'
        '\n'
        'def _mkey(move: dict[int, tuple[Site, Site]]):\n'
        '    srcs = [src for src, _ in move.values()]\n'
        '    return (min(y for _, y in srcs), min(x for x, _ in srcs), len(move))\n'
        '\n'
        '\n'
        'def _merge(moves, occupant, pair_budget: int = 400):\n'
        '    """Agglomerative merging: fusing two legal moves never costs more than keeping them apart."""\n'
        '    moves = list(moves)\n'
        '    if len(moves) < 2:\n'
        '        return moves\n'
        '    calls = 0\n'
        '    changed = True\n'
        '    while changed:\n'
        '        changed = False\n'
        '        moves.sort(key=_mkey)\n'
        '        n = len(moves)\n'
        '        best = None\n'
        '        for i in range(n):\n'
        '            for j in range(i + 1, n):\n'
        '                if n > 8 and j > i + 3:\n'
        '                    break\n'
        '                a, b = moves[i], moves[j]\n'
        '                if not a.keys().isdisjoint(b.keys()):\n'
        '                    continue\n'
        '                merged = {**a, **b}\n'
        '                if move_params(merged, occupant) is None:\n'
        '                    continue\n'
        '                calls += 1\n'
        '                saving = move_cost(a) + move_cost(b) - move_cost(merged)\n'
        '                if best is None or saving > best[0] + 1e-12:\n'
        '                    best = (saving, i, j)\n'
        '                if calls > pair_budget:\n'
        '                    break\n'
        '            if calls > pair_budget:\n'
        '                break\n'
        '        if best is not None:\n'
        '            _, i, j = best\n'
        '            moves[i] = {**moves[i], **moves[j]}\n'
        '            moves.pop(j)\n'
        '            changed = True\n'
        '    return moves\n'
        '\n'
        '\n'
        'def _plan_group(atoms: dict[int, tuple[Site, Site]], occupant: dict[Site, int]):\n'
        '    """Plan the moves of one sub-phase: column runs per (source row, target row), then fuse them."""\n'
        '    if not atoms:\n'
        '        return []\n'
        '    by_row: dict[tuple[int, int], list[int]] = defaultdict(list)\n'
        '    for q, (src, dst) in atoms.items():\n'
        '        by_row[(src[1], dst[1])].append(q)\n'
        '    moves = []\n'
        '    for key in sorted(by_row):\n'
        '        qubits = sorted(by_row[key], key=lambda q: atoms[q][0][0])\n'
        '        current: dict[int, tuple[Site, Site]] = {}\n'
        '        for q in qubits:\n'
        '            if not current:\n'
        '                current = {q: atoms[q]}\n'
        '                continue\n'
        '            candidate = {**current, q: atoms[q]}\n'
        '            if move_params(candidate, occupant) is not None:\n'
        '                current = candidate\n'
        '            else:\n'
        '                moves.append(current)\n'
        '                current = {q: atoms[q]}\n'
        '        if current:\n'
        '            moves.append(current)\n'
        '    return _merge(moves, occupant)\n'
        '\n'
        '\n'
        'def _plan_segment(pairs, targets, visitors, pos: dict[int, Site]):\n'
        '    """(up moves, cz list, down moves) for one segment; every atom ends where it started."""\n'
        '    storage_occ = {site: q for q, site in pos.items()}\n'
        '\n'
        '    atoms_v = {q: (pos[q], targets[q]) for q in visitors}\n'
        '    occ = dict(storage_occ)\n'
        '    up_v = _plan_group(atoms_v, occ)\n'
        '    for q in visitors:\n'
        '        occ.pop(pos[q], None)\n'
        '    atoms_h = {q: (pos[q], targets[q]) for q in targets if q not in visitors}\n'
        '    up_h = _plan_group(atoms_h, occ)\n'
        '\n'
        '    ent_occ = {site: q for q, site in targets.items()}\n'
        '    down_v = _plan_group({q: (targets[q], pos[q]) for q in visitors}, dict(ent_occ))\n'
        '    for q in visitors:\n'
        '        ent_occ.pop(targets[q], None)\n'
        '    down_h = _plan_group({q: (targets[q], pos[q]) for q in targets if q not in visitors}, dict(ent_occ))\n'
        '\n'
        '    return up_v + up_h, list(pairs), down_v + down_h\n'
        '\n'
        '\n'
        'def _segment_cost(segments) -> float:\n'
        '    total = 0.0\n'
        '    for up, _, down in segments:\n'
        '        for move in up:\n'
        '            total += move_cost(move)\n'
        '        for move in down:\n'
        '            total += move_cost(move)\n'
        '    return total\n'
        '\n'
        '\n'
        'def _plan_strategy(pairs, pos: dict[int, Site], strategy: str):\n'
        '    return _plan_assignment(assign_targets(pairs, pos, strategy), pos)\n'
        '\n'
        '\n'
        'def _plan_assignment(assignment, pos: dict[int, Site]):\n'
        '    targets, visitors, assigned, overflow = assignment\n'
        '    segments = [_plan_segment(assigned, targets, visitors, pos)] if assigned else []\n'
        '    if overflow:\n'
        '        segments.extend(plan_segments(overflow, pos))\n'
        '    return segments\n'
        '\n'
        '\n'
        'def plan_segments(pairs, pos: dict[int, Site]):\n'
        '    """One `(up, czs, down)` triple per segment, planned with both target strategies, best kept."""\n'
        '    if not pairs:\n'
        '        return []\n'
        '    compact = assign_targets(pairs, pos, "compact")\n'
        '    segments = _plan_assignment(compact, pos)\n'
        '    if len(pairs) > 1:\n'
        '        flat = assign_targets(pairs, pos, "flat")\n'
        '        if flat[0] != compact[0]:\n'
        '            alternative = _plan_assignment(flat, pos)\n'
        '            if _segment_cost(alternative) < _segment_cost(segments) - 1e-12:\n'
        '                return alternative\n'
        '    return segments\n'
        '\n'
        '\n'
        'def plan_moves(pairs, pos: dict[int, Site]):\n'
        '    """(up moves, cz list, down moves) for one round, flattened over its segments."""\n'
        '    segments = plan_segments(pairs, pos)\n'
        '    up = [move for segment in segments for move in segment[0]]\n'
        '    czs = [cz for segment in segments for cz in segment[1]]\n'
        '    down = [move for segment in segments for move in segment[2]]\n'
        '    return up, czs, down\n'
        '\n'
        '\n'
        'def _round_cost(pairs, pos) -> float:\n'
        '    return _segment_cost(plan_segments(pairs, pos))\n'
        '\n'
        '\n'
        'def plan_cost(rounds, pos) -> float:\n'
        '    return sum(_round_cost(phase.pairs, pos) for phase in rounds)\n'
        '\n'
        '\n'
        '# ------------------------------------------------------------------ 6. placement\n'
        '\n'
        '\n'
        'def _row_proxy(rounds, pos) -> float:\n'
        '    """Cheap stand-in for the plan cost: one vertical trip per host row of a round, both ways."""\n'
        '    total = 0.0\n'
        '    for phase in rounds:\n'
        '        rows = set()\n'
        '        for pair in phase.pairs:\n'
        '            u, v = pair[0], pair[1]\n'
        '            yu, yv = pos[u][1], pos[v][1]\n'
        '            rows.add(yu if yu <= yv else yv)\n'
        '        for y in rows:\n'
        '            total += ENT_Y0 - y\n'
        '    return 2.0 * total\n'
        '\n'
        '\n'
        'def _layout_linear(n: int):\n'
        '    return {q: (q % 10, 9 - q // 10) for q in range(n)}\n'
        '\n'
        '\n'
        'def _layout_boustro(n: int):\n'
        '    return {q: ((q % 10) if (q // 10) % 2 == 0 else 9 - (q % 10), 9 - q // 10) for q in range(n)}\n'
        '\n'
        '\n'
        'def _layout_path(n: int, weight, activity):\n'
        '    if n == 0:\n'
        '        return {}\n'
        '    order = []\n'
        '    used = set()\n'
        '    current = max(range(n), key=lambda q: (activity.get(q, 0), -q))\n'
        '    order.append(current)\n'
        '    used.add(current)\n'
        '    while len(order) < n:\n'
        '        best = None\n'
        '        for q in range(n):\n'
        '            if q in used:\n'
        '                continue\n'
        '            key = (weight.get((current, q), 0), activity.get(q, 0), -q)\n'
        '            if best is None or key > best[0]:\n'
        '                best = (key, q)\n'
        '        order.append(best[1])\n'
        '        used.add(best[1])\n'
        '        current = best[1]\n'
        '    return {q: ((j % 10) if (j // 10) % 2 == 0 else 9 - (j % 10), 9 - j // 10) for j, q in enumerate(order)}\n'
        '\n'
        '\n'
        'def _layout_pair_slots(n: int, weight, activity):\n'
        '    """Pair the busiest partners into one storage row and fill rows 9 upwards."""\n'
        '    ordered = sorted(weight.items(), key=lambda kv: (-kv[1], kv[0]))\n'
        '    free = set(range(n))\n'
        '    matched = []\n'
        '    for (u, v), w in ordered:\n'
        '        if u in free and v in free:\n'
        '            free.discard(u)\n'
        '            free.discard(v)\n'
        '            matched.append(((u, v), w))\n'
        '    matched.sort(key=lambda item: (-(item[1]), -activity[item[0][0]] - activity[item[0][1]], item[0]))\n'
        '    pos: dict[int, Site] = {}\n'
        '    slots = [((2 * k, y), (2 * k + 1, y)) for y in range(9, -1, -1) for k in range(N_PAIRS_PER_ROW)]\n'
        '    for index, ((u, v), _) in enumerate(matched):\n'
        '        if index >= len(slots):\n'
        '            break\n'
        '        a, b = slots[index]\n'
        '        pos[u] = a\n'
        '        pos[v] = b\n'
        '    rest = sorted(free, key=lambda q: (-activity[q], q))\n'
        '    taken = set(pos.values())\n'
        '    remaining_sites = [(x, y) for y in range(9, -1, -1) for x in range(10) if (x, y) not in taken]\n'
        '    for q, site in zip(rest, remaining_sites):\n'
        '        pos[q] = site\n'
        '    return pos\n'
        '\n'
        '\n'
        'def initial_placement(n: int, rounds) -> dict[int, Site]:\n'
        '    """Best of a few deterministic layouts, each pairing busy partners in a storage row."""\n'
        '    weight: dict[tuple[int, int], int] = defaultdict(int)\n'
        '    for phase in rounds:\n'
        '        for u, v, _ in phase.pairs:\n'
        '            key = (u, v) if u < v else (v, u)\n'
        '            weight[key] += 1\n'
        '    activity: dict[int, int] = defaultdict(int)\n'
        '    for (u, v), w in weight.items():\n'
        '        activity[u] += w\n'
        '        activity[v] += w\n'
        '\n'
        '    candidates = [\n'
        '        _layout_linear(n),\n'
        '        _layout_boustro(n),\n'
        '        _layout_path(n, weight, activity),\n'
        '        _layout_pair_slots(n, weight, activity),\n'
        '    ]\n'
        '    if not rounds:\n'
        '        return candidates[0]\n'
        '    candidates.sort(key=lambda layout: _row_proxy(rounds, layout))\n'
        '    if n * len(rounds) <= 40000:\n'
        '        return min(candidates, key=lambda layout: plan_cost(rounds, layout))\n'
        '    return candidates[0]\n'
        '\n'
        '\n'
        'def _budget(n: int, n_rounds: int) -> int:\n'
        '    """Deterministic work budget of the placement search, in planned pair-rounds.\n'
        '\n'
        '    One unit = re-planning one interaction pair of one round (~0.15-0.3 ms here). The budget is a\n'
        '    pure function of the circuit size, so the same input always yields the same placement, whatever\n'
        '    the machine load or whatever ran earlier in the process."""\n'
        '    if n_rounds > 1000:\n'
        '        return 10_000\n'
        '    if n <= 16:\n'
        '        return 20_000\n'
        '    if n <= 24:\n'
        '        return 40_000\n'
        '    if n <= 50:\n'
        '        return 50_000\n'
        '    return 10_000\n'
        '\n'
        '\n'
        'def optimise_placement(rounds, pos: dict[int, Site], budget: int) -> dict[int, Site]:\n'
        '    """Incremental hill climbing on the plan cost: swap two sites, or move an atom to a free one.\n'
        '\n'
        '    Deterministic: fixed seed and a fixed work budget (see `_budget`), no wall clock."""\n'
        '    if not rounds or budget <= 0:\n'
        '        return pos\n'
        '    rng = random.Random(12345)\n'
        '    pos = dict(pos)\n'
        '    qubits = sorted(pos)\n'
        '    sites = [(x, y) for y in range(9, -1, -1) for x in range(10)]\n'
        '    used = set(pos.values())\n'
        '    free_sites = [site for site in sites if site not in used]\n'
        '    pred_of_round = [[(u, v) for (u, v, _) in phase.pairs] for phase in rounds]\n'
        '    involved = [tuple(sorted({q for u, v in pr for q in (u, v)})) for pr in pred_of_round]\n'
        '    pred_key = [tuple(sorted(pr)) for pr in pred_of_round]\n'
        '    touch: dict[int, list[int]] = defaultdict(list)\n'
        '    for i, qs in enumerate(involved):\n'
        '        for q in qs:\n'
        '            touch[q].append(i)\n'
        '    active = [q for q in qubits if touch[q]]\n'
        '\n'
        '    cache: dict[Any, float] = {}\n'
        '    work = [0]\n'
        '\n'
        '    def rcost(i: int, p: dict[int, Site]) -> float:\n'
        "        # Keyed on the round's own atoms only: a heuristic (the ghost check also sees other atoms),\n"
        '        # measured to beat an exact full-placement key because it allows far more proposals.\n'
        '        key = (pred_key[i], tuple(p[q] for q in involved[i]))\n'
        '        value = cache.get(key)\n'
        '        if value is None:\n'
        '            value = _round_cost(pred_of_round[i], p)\n'
        '            cache[key] = value\n'
        '            k = len(pred_of_round[i])\n'
        '            work[0] += max(1, k if k <= 8 else 2 * k)  # big rounds plan super-linearly\n'
        '        return value\n'
        '\n'
        '    cost = [rcost(i, pos) for i in range(len(rounds))]\n'
        '    if not active or work[0] > budget // 2:\n'
        '        return dict(pos)\n'
        '    site_of = {q: pos[q] for q in qubits}\n'
        '    holder = {site: q for q, site in site_of.items()}\n'
        '    proposals_left = 3 * budget  # guard: stop even if most proposals hit the cache\n'
        '\n'
        '    def swap(u: int, v: int) -> None:\n'
        '        keys = touch[u] + touch[v]\n'
        '        target = site_of[v]\n'
        '        origin = site_of[u]\n'
        '        if not keys or target == origin:\n'
        '            return\n'
        '        unique = set(keys)\n'
        '        old = 0.0\n'
        '        for i in unique:\n'
        '            old += cost[i]\n'
        '        pos[u], pos[v] = target, origin\n'
        '        site_of[u], site_of[v] = target, origin\n'
        '        new = 0.0\n'
        '        for i in unique:\n'
        '            new += rcost(i, pos)\n'
        '        if new < old - 1e-12:\n'
        '            for i in unique:\n'
        '                cost[i] = rcost(i, pos)\n'
        '            holder[target] = u\n'
        '            holder[origin] = v\n'
        '        else:\n'
        '            pos[u], pos[v] = origin, target\n'
        '            site_of[u], site_of[v] = origin, target\n'
        '\n'
        '    def relocate(u: int, site: Site) -> None:\n'
        '        keys = touch[u]\n'
        '        if not keys:\n'
        '            return\n'
        '        origin = site_of[u]\n'
        '        unique = set(keys)\n'
        '        old = 0.0\n'
        '        for i in unique:\n'
        '            old += cost[i]\n'
        '        pos[u] = site\n'
        '        site_of[u] = site\n'
        '        new = 0.0\n'
        '        for i in unique:\n'
        '            new += rcost(i, pos)\n'
        '        if new < old - 1e-12:\n'
        '            for i in unique:\n'
        '                cost[i] = rcost(i, pos)\n'
        '            holder.pop(origin, None)\n'
        '            holder[site] = u\n'
        '            free_sites.remove(site)\n'
        '            free_sites.append(origin)\n'
        '        else:\n'
        '            pos[u] = origin\n'
        '            site_of[u] = origin\n'
        '\n'
        '    while work[0] < budget and proposals_left > 0:\n'
        '        proposals_left -= 1\n'
        '        roll = rng.random()\n'
        '        if roll < 0.3 and free_sites:\n'
        '            relocate(rng.choice(active), free_sites[rng.randrange(len(free_sites))])\n'
        '        elif active:\n'
        '            swap(active[rng.randrange(len(active))], qubits[rng.randrange(len(qubits))])\n'
        '        if len(cache) > 300000:\n'
        '            cache.clear()\n'
        '    return dict(pos)\n'
        '\n'
        '\n'
        '# ------------------------------------------------------------------ 7. parking emission\n'
        '\n'
        '\n'
        'PARK = False\n'
        '"""Keep an atom already in the entangling zone for its next `cz`. Measured 40 % worse: the partner\n'
        'is forced into the parked atom\'s slot, which is usually far, so this stays off."""\n'
        '\n'
        '\n'
        'def _are_paired(a: Site, b: Site) -> bool:\n'
        '    if a[1] != b[1] or a[1] < ENT_Y0:\n'
        '        return False\n'
        '    low, high = (a[0], b[0]) if a[0] < b[0] else (b[0], a[0])\n'
        '    return high == low + 1 and low % 2 == 0\n'
        '\n'
        '\n'
        'def _complement(site: Site) -> Site:\n'
        '    x, y = site\n'
        '    return (x + 1, y) if x % 2 == 0 else (x - 1, y)\n'
        '\n'
        '\n'
        'def _occupied_pairs(occ: dict[Site, int]):\n'
        '    return {frozenset((occ[s], occ[_complement(s)])) for s in occ if s[1] >= ENT_Y0 and s[0] % 2 == 0 and _complement(s) in occ}\n'
        '\n'
        '\n'
        'def _park_actions(pairs, current, home, occ, ops_qubits):\n'
        '    """Plan one round keeping the atoms that are already where their next `cz` needs them.\n'
        '\n'
        "    Returns `(before, after)`: `before` are move dicts emitted before the round's 1q ops, `after`\n"
        '    a list of `("move", atoms)` / `("cz", pair)` entries emitted afterwards, or `None` if the round\n'
        '    cannot be planned safely (the caller then falls back to the static plan).\n'
        '    """\n'
        '    cur = dict(current)\n'
        '    o = dict(occ)\n'
        '    before = []\n'
        '    after = []\n'
        '\n'
        '    def apply(atoms):\n'
        '        if move_params(atoms, o) is None:\n'
        '            return False\n'
        '        for q, (src, _) in atoms.items():\n'
        '            o.pop(src, None)\n'
        '        for q, (_, dst) in atoms.items():\n'
        '            o[dst] = q\n'
        '            cur[q] = dst\n'
        '        return True\n'
        '\n'
        '    pair_of = {}\n'
        '    for pair in pairs:\n'
        '        pair_of[pair[0]] = pair\n'
        '        pair_of[pair[1]] = pair\n'
        '\n'
        '    ready = []\n'
        '    for pair in pairs:\n'
        '        u, v = pair[0], pair[1]\n'
        '        if u in ops_qubits or v in ops_qubits:\n'
        '            continue\n'
        '        if cur[u][1] >= ENT_Y0 and cur[v][1] >= ENT_Y0 and _are_paired(cur[u], cur[v]):\n'
        '            ready.append(pair)\n'
        '    ready_keys = {id(pair) for pair in ready}\n'
        '\n'
        '    parked: dict[int, tuple[Any, Site]] = {}\n'
        '    for pair in pairs:\n'
        '        if id(pair) in ready_keys:\n'
        '            continue\n'
        '        for q in (pair[0], pair[1]):\n'
        '            if q in parked or q in ops_qubits or cur[q][1] < ENT_Y0:\n'
        '                continue\n'
        '            if o.get(_complement(cur[q])) is not None:\n'
        '                continue\n'
        '            parked[q] = (pair, _complement(cur[q]))\n'
        '\n'
        '    stay = set(parked)\n'
        '    for pair in ready:\n'
        '        stay.add(pair[0])\n'
        '        stay.add(pair[1])\n'
        '    dropping = {q: (cur[q], home[q]) for q in sorted(cur) if cur[q][1] >= ENT_Y0 and q not in stay}\n'
        '\n'
        '    # lower in two sub-phases: odd entangling columns first, then even ones (rectangles stay clean)\n'
        '    for parity in (1, 0):\n'
        '        selection = {q: v for q, v in dropping.items() if v[0][0] % 2 == parity}\n'
        '        if not selection:\n'
        '            continue\n'
        '        for atoms in _plan_group(selection, o):\n'
        '            if not apply(atoms):\n'
        '                return None\n'
        '            before.append(atoms)\n'
        '\n'
        '    static = [\n'
        '        pair\n'
        '        for pair in pairs\n'
        '        if id(pair) not in ready_keys and pair[0] not in parked and pair[1] not in parked\n'
        '    ]\n'
        '    targets: dict[int, Site] = {}\n'
        '    visitors: set[int] = set()\n'
        '    if static:\n'
        '        options = [assign_targets(static, cur, "compact"), assign_targets(static, cur, "flat")]\n'
        '        best = None\n'
        '        for option in options:\n'
        '            option_targets, option_visitors, _, overflow = option\n'
        '            if overflow:\n'
        '                return None\n'
        '            if any(q not in option_targets for pair in static for q in (pair[0], pair[1])):\n'
        '                continue\n'
        '            cost = sum(max(_trip(cur[q], option_targets[q]) for q in (pair[0], pair[1])) for pair in static)\n'
        '            if best is None or cost < best[0] - 1e-12:\n'
        '                best = (cost, option_targets, option_visitors)\n'
        '        if best is None:\n'
        '            return None\n'
        '        targets.update(best[1])\n'
        '        visitors.update(best[2])\n'
        '    for q, (pair, other_site) in parked.items():\n'
        '        targets[q] = cur[q]\n'
        '        partner = pair[1] if pair[0] == q else pair[0]\n'
        '        targets[partner] = other_site\n'
        '\n'
        '    lifting = {q: (cur[q], targets[q]) for q in targets if cur[q] != targets[q]}\n'
        '    for parity in (1, 0):\n'
        '        selection = {q: v for q, v in lifting.items() if v[0][0] % 2 == parity}\n'
        '        if not selection:\n'
        '            continue\n'
        '        for atoms in _plan_group(selection, o):\n'
        '            if not apply(atoms):\n'
        '                return None\n'
        '            after.append(("move", atoms))\n'
        '\n'
        '    for pair in pairs:\n'
        '        u, v = pair[0], pair[1]\n'
        '        if o.get(targets.get(u, cur[u])) != u or o.get(targets.get(v, cur[v])) != v:\n'
        '            return None\n'
        '        after.append(("cz", pair))\n'
        '    occupied = _occupied_pairs(o)\n'
        '    if not occupied <= {frozenset(pair[:2]) for pair in pairs}:\n'
        '        return None\n'
        '    # every interaction pair that holds two atoms gets exactly one pulse this segment\n'
        '    counts = {}\n'
        '    for entry in after:\n'
        '        if entry[0] == "cz":\n'
        '            counts[frozenset(entry[1][:2])] = counts.get(frozenset(entry[1][:2]), 0) + 1\n'
        '    if any(counts.get(pair, 0) != 1 for pair in occupied):\n'
        '        return None\n'
        '    return before, after\n'
        '\n'
        '\n'
        'def _trip(src: Site, dst: Site) -> float:\n'
        '    return math.dist(_physical(src), _physical(dst))\n'
        '\n'
        '\n'
        'def _static_actions(pairs, current, home, occ):\n'
        '    """Today\'s plan: lower everything that is up, then lift/cz/lower the round from `home`."""\n'
        '    cur = dict(current)\n'
        '    o = dict(occ)\n'
        '    before = []\n'
        '    dropping = {q: (cur[q], home[q]) for q in sorted(cur) if cur[q][1] >= ENT_Y0}\n'
        '    for parity in (1, 0):\n'
        '        selection = {q: v for q, v in dropping.items() if v[0][0] % 2 == parity}\n'
        '        if not selection:\n'
        '            continue\n'
        '        for atoms in _plan_group(selection, o):\n'
        '            if move_params(atoms, o) is None:\n'
        '                return None\n'
        '            for q, (src, _) in atoms.items():\n'
        '                o.pop(src, None)\n'
        '            for q, (_, dst) in atoms.items():\n'
        '                o[dst] = q\n'
        '                cur[q] = dst\n'
        '            before.append(atoms)\n'
        '    after = []\n'
        '    for up, czs, down in plan_segments(pairs, cur):\n'
        '        for atoms in up:\n'
        '            if move_params(atoms, o) is None:\n'
        '                return None\n'
        '            for q, (src, _) in atoms.items():\n'
        '                o.pop(src, None)\n'
        '            for q, (_, dst) in atoms.items():\n'
        '                o[dst] = q\n'
        '                cur[q] = dst\n'
        '            after.append(("move", atoms))\n'
        '        for pair in czs:\n'
        '            after.append(("cz", pair))\n'
        '        for atoms in down:\n'
        '            if move_params(atoms, o) is None:\n'
        '                return None\n'
        '            for q, (src, _) in atoms.items():\n'
        '                o.pop(src, None)\n'
        '            for q, (_, dst) in atoms.items():\n'
        '                o[dst] = q\n'
        '                cur[q] = dst\n'
        '            after.append(("move", atoms))\n'
        '    return before, after\n'
        '\n'
        '\n'
        'def _emit_parked(native: QuantumCircuit, rounds, home: dict[int, Site]):\n'
        '    """Emit the whole circuit keeping atoms in the zone across rounds where that pays."""\n'
        '    out = native.copy_empty_like()\n'
        '    qbits = out.qubits\n'
        '    cbits = out.clbits\n'
        '    current = dict(home)\n'
        '    occ = {site: q for q, site in current.items()}\n'
        '    distance = 0.0\n'
        '\n'
        '    def do_move(atoms):\n'
        '        nonlocal distance\n'
        '        params = move_params(atoms, occ)\n'
        '        if params is None:\n'
        '            raise AssertionError("parked emission planned an illegal move")\n'
        '        for q, (src, _) in atoms.items():\n'
        '            occ.pop(src, None)\n'
        '        for q, (_, dst) in atoms.items():\n'
        '            occ[dst] = q\n'
        '            current[q] = dst\n'
        '        _move(out, list(atoms), *params)\n'
        '        distance += move_cost(atoms)\n'
        '\n'
        '    moved = True\n'
        '    for index, phase in enumerate(rounds):\n'
        '        pairs = phase.pairs\n'
        '        ops_qubits = set()\n'
        '        for op, qargs, cargs in phase.ops:\n'
        '            if op.name != "measure":\n'
        '                ops_qubits.update(qargs)\n'
        '        plan = None\n'
        '        if PARK and pairs:\n'
        '            plan = _park_actions(pairs, current, home, occ, ops_qubits)\n'
        '        if plan is None:\n'
        '            plan = _static_actions(pairs, current, home, occ)\n'
        '            if plan is None:\n'
        '                break\n'
        '        before, after = plan\n'
        '        if pairs and not moved and not before and not any(entry[0] == "move" for entry in after):\n'
        '            # two cz segments with nothing in between: break the segment unless the pair set matches\n'
        '            if not _occupied_pairs(occ) <= {frozenset(pair[:2]) for pair in pairs}:\n'
        '                spare = [q for pair in pairs for q in (pair[0], pair[1]) if q not in ops_qubits and current[q][1] >= ENT_Y0]\n'
        '                if spare:\n'
        '                    q = spare[0]\n'
        '                    site = current[q]\n'
        '                    down = {q: (site, home[q])}\n'
        '                    if move_params(down, occ) is not None:\n'
        '                        do_move(down)\n'
        '                        up = {q: (home[q], site)}\n'
        '                        if move_params(up, occ) is not None:\n'
        '                            do_move(up)\n'
        '        for atoms in before:\n'
        '            do_move(atoms)\n'
        '        for op, qargs, cargs in phase.ops:\n'
        '            out.append(op, [qbits[q] for q in qargs], [cbits[c] for c in cargs])\n'
        '        for entry in after:\n'
        '            if entry[0] == "move":\n'
        '                do_move(entry[1])\n'
        '                moved = True\n'
        '            else:\n'
        '                u, v = entry[1][0], entry[1][1]\n'
        '                out.append(entry[1][2], [qbits[u], qbits[v]])\n'
        '                moved = False\n'
        '    return out, distance\n'
        '\n'
        '\n'
        '# ------------------------------------------------------------------ 8. orchestrator\n'
        '\n'
        '\n'
        'def _emit_move(out: QuantumCircuit, atoms: dict[int, tuple[Site, Site]]) -> None:\n'
        '    rows, cols, new_rows, new_cols = move_params(atoms, {})\n'
        '    _move(out, list(atoms), rows, cols, new_rows, new_cols)\n'
        '\n'
        '\n'
        'DEPTH_WEIGHT = 2.922\n'
        '"""Score-neutral exchange rate between one unit of moved distance and one unit of depth."""\n'
        '\n'
        '\n'
        'def _emit_static(native: QuantumCircuit, rounds, pos):\n'
        '    """Emit today\'s plan: lift every round\'s atoms, one `cz` per pair, lower them again."""\n'
        '    out = native.copy_empty_like()\n'
        '    qbits = out.qubits\n'
        '    cbits = out.clbits\n'
        '    distance = 0.0\n'
        '    for phase in rounds:\n'
        '        for op, qargs, cargs in phase.ops:\n'
        '            out.append(op, [qbits[q] for q in qargs], [cbits[c] for c in cargs])\n'
        '        for up, czs, down in plan_segments(phase.pairs, pos):\n'
        '            for atoms in up:\n'
        '                _emit_move(out, atoms)\n'
        '                distance += move_cost(atoms)\n'
        '            for u, v, op in czs:\n'
        '                out.append(op, [qbits[u], qbits[v]])\n'
        '            for atoms in down:\n'
        '                _emit_move(out, atoms)\n'
        '                distance += move_cost(atoms)\n'
        '    return out, distance\n'
        '\n'
        '\n'
        'def _candidate(native: QuantumCircuit, n: int, division: int = 1):\n'
        '    """Plan and emit one candidate; returns the best `(objective, circuit, home placement)`."""\n'
        '    rounds = schedule_rounds(native)\n'
        '    pos = initial_placement(n, rounds)\n'
        '    pos = optimise_placement(rounds, pos, _budget(n, len(rounds)) // division)\n'
        '    depth = native.depth()\n'
        '    out, distance = _emit_static(native, rounds, pos)\n'
        '    best = (distance + DEPTH_WEIGHT * depth, out, pos)\n'
        '    if PARK and rounds:\n'
        '        try:\n'
        '            parked, parked_distance = _emit_parked(native, rounds, pos)\n'
        '        except AssertionError:\n'
        '            return best\n'
        '        objective = parked_distance + DEPTH_WEIGHT * depth\n'
        '        if objective < best[0] - 1e-9:\n'
        '            best = (objective, parked, pos)\n'
        '    return best\n'
        '\n'
        '\n'
        'def compile_circuit(circuit: QuantumCircuit, architecture_spec: Any):\n'
        '    n = circuit.num_qubits\n'
        '    plain = native_circuit(circuit)\n'
        '    best = _candidate(plain, n)\n'
        '    oriented = native_circuit(zz_orient(circuit))\n'
        '    if _native_key(oriented) != _native_key(plain):\n'
        '        alternative = _candidate(oriented, n, 2)\n'
        '        if alternative[0] < best[0] - 1e-9:\n'
        '            best = alternative\n'
        '    return best[1], Architecture(best[2], spec=architecture_spec)\n'
