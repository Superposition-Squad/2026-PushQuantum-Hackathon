        '        return start * spacing + pair * 2 * spacing + slot * float(pairs["distance"])\n'
        '\n'
        '    def dist(self, a: Site, b: Site) -> float:\n'
        '        pa, pb = self.phys[a], self.phys[b]\n'
        '        return math.hypot(pa[0] - pb[0], pa[1] - pb[1])\n'
        '\n'
        '    def in_ent(self, s: Site) -> bool:\n'
        '        return self.zone_of.get(s) == self.ent\n'
        '\n'
        '    def in_storage(self, s: Site) -> bool:\n'
        '        return self.zone_of.get(s) == self.storage\n'
        '\n'
        '\n'
        '# ---------------------------------------------------------------- 1q algebra\n'
        '\n'
        'I2 = np.eye(2, dtype=complex)\n'
        'PX = np.array([[0, 1], [1, 0]], dtype=complex)\n'
        'PY = np.array([[0, -1j], [1j, 0]], dtype=complex)\n'
        'PZ = np.array([[1, 0], [0, -1]], dtype=complex)\n'
        'PAULI = {"X": PX, "Y": PY, "Z": PZ}\n'
        'HAD = np.array([[1, 1], [1, -1]], dtype=complex) / math.sqrt(2)\n'
        'SGATE = np.array([[1, 0], [0, 1j]], dtype=complex)\n'
        '\n'
        '\n'
        'def _is_identity(u: np.ndarray, tol: float = 1e-9) -> bool:\n'
        '    return abs(abs(np.trace(u)) - 2.0) < tol\n'
        '\n'
        '\n'
        'def _pauli_of(m: np.ndarray) -> tuple[str, int] | None:\n'
        '    """(P, sign) if m = sign * P for a Pauli P and sign = +-1."""\n'
        '    for name, p in PAULI.items():\n'
        '        c = np.trace(p @ m) / 2\n'
        '        if abs(abs(c) - 1) < 1e-9 and abs(c.imag) < 1e-9 and np.allclose(m, c * p, atol=1e-9):\n'
        '            return name, (1 if c.real > 0 else -1)\n'
        '    return None\n'
        '\n'
        '\n'
        'def _cliffords() -> list[np.ndarray]:\n'
        '    found: list[np.ndarray] = [I2]\n'
        '    frontier = [I2]\n'
        '    while frontier:\n'
        '        nxt = []\n'
        '        for u in frontier:\n'
        '            for g in (HAD, SGATE):\n'
        '                v = g @ u\n'
        '                if not any(_is_identity(v.conj().T @ w) for w in found):\n'
        '                    found.append(v)\n'
        '                    nxt.append(v)\n'
        '        frontier = nxt\n'
        '    return found\n'
        '\n'
        '\n'
        '_CLIFF = _cliffords()\n'
        '_BASIS: dict[tuple[str, str], np.ndarray] = {}\n'
        'for _p in "XYZ":\n'
        '    for _t in "XZ":\n'
        '        for _w in _CLIFF:\n'
        '            if np.allclose(_w @ PAULI[_p] @ _w.conj().T, PAULI[_t], atol=1e-9):\n'
        '                _BASIS[(_p, _t)] = _w\n'
        '                break\n'
        '\n'
        '\n'
        'def basis_change(p: str, target: str) -> np.ndarray:\n'
        '    """A Clifford W with W P W^+ = +target."""\n'
        '    return _BASIS[(p, target)]\n'
        '\n'
        '\n'
        'def _rx(theta: float) -> np.ndarray:\n'
        '    c, s = math.cos(theta / 2), math.sin(theta / 2)\n'
        '    return np.array([[c, -1j * s], [-1j * s, c]], dtype=complex)\n'
        '\n'
        '\n'
        '_ZXZ = OneQubitEulerDecomposer("ZXZ")\n'
        '_XZX = OneQubitEulerDecomposer("XZX")\n'
        '\n'
        '\n'
        'def synth_1q(u: np.ndarray) -> list[tuple[str, float]]:\n'
        '    """Fewest rx/rz gates (time order) equal to u up to global phase."""\n'
        '    if _is_identity(u):\n'
        '        return []\n'
        '    best = None\n'
        '    for dec in (_ZXZ, _XZX):\n'
        '        qc = dec(u, simplify=True, atol=1e-10)\n'
        '        gates = [(ins.operation.name, float(ins.operation.params[0])) for ins in qc.data]\n'
        '        gates = [(n, a) for n, a in gates if abs(math.remainder(a, 4 * math.pi)) > 1e-10]\n'
        '        if best is None or len(gates) < len(best):\n'
        '            best = gates\n'
        '    return best\n'
        '\n'
        '\n'
        '# ---------------------------------------------------------------- front end\n'
        '\n'
        'U1, ROT, CZB, MEAS = "u1", "rot", "czb", "meas"\n'
        '_SKIP = {"barrier", "delay"}\n'
        '_KNOWN_2Q = {"cx", "cz", "rzz"}\n'
        '\n'
        '\n'
        'class Op:\n'
        '    __slots__ = ("kind", "qubits", "mat", "paulis", "theta", "basis", "clbit", "idx", "comm")\n'
        '\n'
        '    def __init__(self, kind, qubits, mat=None, paulis=None, theta=0.0, basis=None, clbit=None):\n'
        '        self.kind, self.qubits, self.mat, self.paulis = kind, tuple(qubits), mat, paulis\n'
        '        self.theta, self.basis, self.clbit, self.idx = theta, basis, clbit, -1\n'
        '        self.comm = None\n'
        '        if kind == U1:\n'
        '            self.comm = frozenset(p for p, m in PAULI.items() if np.allclose(mat @ m, m @ mat, atol=1e-9))\n'
        '\n'
        '\n'
        'def _raw_gates(circuit: QuantumCircuit):\n'
        '    """(name, qubits, clbits, op) with qubit/clbit indices; unknown multi-qubit gates are decomposed."""\n'
        '    names = {ins.operation.name for ins in circuit.data}\n'
        '    ok = all(\n'
        '        n in _SKIP or n == "measure" or n in _KNOWN_2Q or (ins.operation.num_qubits == 1 and not ins.operation.num_clbits)\n'
        '        for ins in circuit.data\n'
        '        for n in [ins.operation.name]\n'
        '    )\n'
        '    if not ok:\n'
        '        circuit = transpile(circuit, basis_gates=["u", "cx", "cz", "rzz", "measure"], optimization_level=0)\n'
        '    del names\n'
        '    qi = {b: i for i, b in enumerate(circuit.qubits)}\n'
        '    ci = {b: i for i, b in enumerate(circuit.clbits)}\n'
        '    out = []\n'
        '    for ins in circuit.data:\n'
        '        op = ins.operation\n'
        '        if op.name in _SKIP:\n'
        '            continue\n'
        '        qs = [qi[q] for q in ins.qubits]\n'
        '        cs = [ci[c] for c in ins.clbits]\n'
        '        if op.name == "measure":\n'
        '            out.append(("measure", qs, cs, op))\n'
        '        elif op.name in _KNOWN_2Q:\n'
        '            out.append((op.name, qs, cs, op))\n'
        '        elif op.num_qubits == 1 and not cs:\n'
        '            out.append(("u1", qs, cs, op))\n'
        '        else:\n'
        '            raise Unsupported(f"gate {op.name}")\n'
        '    return out, circuit\n'
        '\n'
        '\n'
        'def front_end(circuit: QuantumCircuit) -> tuple[list[Op], int]:\n'
        '    raw, circuit = _raw_gates(circuit)\n'
        '    n = circuit.num_qubits\n'
        '    mats: dict[int, np.ndarray] = {}\n'
        '    for i, (name, qs, cs, op) in enumerate(raw):\n'
        '        if name == "u1":\n'
        '            mats[i] = Operator(op).data\n'
        '    # per-wire sequences of raw indices\n'
        '    wire: list[list[int]] = [[] for _ in range(n)]\n'
        '    for i, (_, qs, _, _) in enumerate(raw):\n'
        '        for q in qs:\n'
        '            wire[q].append(i)\n'
        '    posw = {}\n'
        '    for q in range(n):\n'
        '        for k, i in enumerate(wire[q]):\n'
        '            posw[(q, i)] = k\n'
        '\n'
        '    def nxt(q, i, d=1):\n'
        '        k = posw[(q, i)] + d\n'
        '        return wire[q][k] if 0 <= k < len(wire[q]) else None\n'
        '\n'
        '    consumed: set[int] = set()\n'
        '    replaced: dict[int, Op] = {}\n'
        '    for i, (name, qs, _, op) in enumerate(raw):\n'
        '        if name != "cx" or i in consumed:\n'
        '            continue\n'
        '        c, t = qs\n'
        '        j = nxt(t, i)\n'
        '        k = nxt(t, j) if j is not None else None\n'
        '        if j is None or k is None or j in consumed or k in consumed:\n'
        '            continue\n'
        '        if raw[j][0] != "u1" or raw[k][0] != "cx" or raw[k][1] != [c, t] or nxt(c, i) != k:\n'
        '            continue\n'
        '        d = mats[j]\n'
        '        if abs(d[0, 1]) > 1e-12 or abs(d[1, 0]) > 1e-12:\n'
        '            continue\n'
        '        theta = float(np.angle(d[1, 1] / d[0, 0]))\n'
        '        paulis = {c: "Z", t: "Z"}\n'
        '        sign = 1\n'
        '        extra: list[int] = []\n'
        '        for q in (c, t):\n'
        '            p, s = nxt(q, i, -1), nxt(q, k, 1)\n'
        '            if p is None or s is None or p in consumed or s in consumed or p == s:\n'
        '                continue\n'
        '            if raw[p][0] != "u1" or raw[s][0] != "u1":\n'
        '                continue\n'
        '            mp, ms = mats[p], mats[s]\n'
        '            if not _is_identity(ms @ mp):\n'
        '                continue\n'
        '            pq = _pauli_of(mp.conj().T @ PZ @ mp)\n'
        '            if pq is None:\n'
        '                continue\n'
        '            paulis[q] = pq[0]\n'
        '            sign *= pq[1]\n'
        '            extra += [p, s]\n'
        '        consumed.update([i, j, k, *extra])\n'
        '        replaced[i] = Op(ROT, (c, t), paulis=(paulis[c], paulis[t]), theta=sign * theta)\n'
        '    ops: list[Op] = []\n'
        '    measured: set[int] = set()\n'
        '    for i, (name, qs, cs, op) in enumerate(raw):\n'
        '        if i in replaced:\n'
        '            ops.append(replaced[i])\n'
        '            continue\n'
        '        if i in consumed:\n'
        '            continue\n'
        '        if any(q in measured for q in qs):\n'
        '            raise Unsupported("gate after measurement")\n'
        '        if name == "u1":\n'
        '            ops.append(Op(U1, qs, mat=mats[i]))\n'
        '        elif name == "measure":\n'
        '            ops.append(Op(MEAS, qs, clbit=cs[0]))\n'
        '            measured.add(qs[0])\n'
        '        elif name == "cx":\n'
        '            ops.append(Op(CZB, qs, paulis=("Z", "X"), basis=(I2, HAD)))\n'
        '        elif name == "cz":\n'
        '            ops.append(Op(CZB, qs, paulis=("Z", "Z"), basis=(I2, I2)))\n'
        '        elif name == "rzz":\n'
        '            ops.append(Op(ROT, qs, paulis=("Z", "Z"), theta=float(op.params[0])))\n'
        '    # elide identity rotations (theta = 0 mod 2pi gives +-identity)\n'
        '    ops = [o for o in ops if not (o.kind == ROT and abs(math.remainder(o.theta, 2 * math.pi)) < 1e-12)]\n'
        '    for k, o in enumerate(ops):\n'
        '        o.idx = k\n'
        '    return ops, n\n'
        '\n'
        '\n'
        'def _pauli_on(o: Op, q: int) -> str:\n'
        '    return o.paulis[o.qubits.index(q)]\n'
        '\n'
        '\n'
        'def _commute(a: Op, b: Op) -> bool:\n'
        '    shared = set(a.qubits) & set(b.qubits)\n'
        '    if not shared:\n'
        '        return True\n'
        '    if a.kind == MEAS or b.kind == MEAS:\n'
        '        return False\n'
        '    if a.kind == U1 and b.kind == U1:\n'
        '        return False\n'
        '    if a.kind == U1 or b.kind == U1:\n'
        '        u, o = (a, b) if a.kind == U1 else (b, a)\n'
        '        return _pauli_on(o, u.qubits[0]) in u.comm\n'
        '    if a.kind == ROT and b.kind == ROT:\n'
        '        anti = sum(_pauli_on(a, q) != _pauli_on(b, q) for q in shared)\n'
        '        return anti % 2 == 0\n'
        '    # at least one single-CZ block: functions of its per-qubit Paulis -> need qubitwise agreement\n'
        '    return all(_pauli_on(a, q) == _pauli_on(b, q) for q in shared)\n'
        '\n'
        '\n'
        'def build_dag(ops: list[Op], n: int):\n'
        '    succ: list[set[int]] = [set() for _ in ops]\n'
        '    indeg = [0] * len(ops)\n'
        '    per_q: list[list[int]] = [[] for _ in range(n)]\n'
        '    for o in ops:\n'
        '        for q in o.qubits:\n'
        '            for j in per_q[q]:\n'
        '                if o.idx not in succ[j] and not _commute(ops[j], o):\n'
        '                    succ[j].add(o.idx)\n'
        '                    indeg[o.idx] += 1\n'
        '            per_q[q].append(o.idx)\n'
        '    return succ, indeg\n'
        '\n'
        '\n'
        '# ---------------------------------------------------------------- machine state + move grouping\n'
        '\n'
        '\n'
        'class State:\n'
        '    """Atom positions with the validator\'s move semantics (strict: one zone per side)."""\n'
        '\n'
        '    def __init__(self, geo: Geo, loading: dict[int, Site]):\n'
        '        self.geo = geo\n'
        '        self.pos = dict(loading)\n'
        '        self.occ = {s: q for q, s in self.pos.items()}\n'
        '\n'
        '    def copy(self) -> "State":\n'
        '        st = State.__new__(State)\n'
        '        st.geo, st.pos, st.occ = self.geo, dict(self.pos), dict(self.occ)\n'
        '        return st\n'
        '\n'
        '    def apply(self, group: list[tuple[int, Site]]) -> tuple[tuple, float]:\n'
        '        """group = [(qubit, target)]; returns (move params, distance). Raises on illegal moves."""\n'
        '        g = self.geo\n'
        '        src = {q: self.pos[q] for q, _ in group}\n'
        '        tgt = dict(group)\n'
        '        xs = [s[0] for s in src.values()]\n'
        '        ys = [s[1] for s in src.values()]\n'
        '        x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)\n'
        '        members = set(src)\n'
        '        for x in range(x0, x1 + 1):\n'
        '            for y in range(y0, y1 + 1):\n'
        '                o = self.occ.get((x, y))\n'
        '                if o is not None and o not in members:\n'
        '                    raise RuntimeError("ghost")\n'
        '        rmap: dict[int, int] = {}\n'
        '        cmap: dict[int, int] = {}\n'
        '        for q in members:\n'
        '            (sx, sy), (tx, ty) = src[q], tgt[q]\n'
        '            if rmap.setdefault(sy, ty) != ty or cmap.setdefault(sx, tx) != tx:\n'
        '                raise RuntimeError("not a product map")\n'
        '        for m in (rmap, cmap):\n'
        '            ks = sorted(m)\n'
        '            if any(m[a] >= m[b] for a, b in itertools.pairwise(ks)):\n'
        '                raise RuntimeError("order not preserved")\n'
        '        zs = {g.zone_of[s] for s in src.values()}\n'
        '        zt = {g.zone_of.get(t) for t in tgt.values()}\n'
        '        if len(zs) != 1 or len(zt) != 1 or None in zt:\n'
        '            raise RuntimeError("rectangle spans zones")\n'
        '        for q in members:\n'
        '            o = self.occ.get(tgt[q])\n'
        '            if o is not None and o not in members:\n'
        '                raise RuntimeError("target occupied")\n'
        '        dist = max(g.dist(src[q], tgt[q]) for q in members)\n'
        '        for q in members:\n'
        '            del self.occ[src[q]]\n'
        '        for q in members:\n'
        '            self.pos[q] = tgt[q]\n'
        '            self.occ[tgt[q]] = q\n'
        '        rows = tuple(range(y0, y1 + 1))\n'
        '        cols = tuple(range(x0, x1 + 1))\n'
        '        new_rows = tuple(rmap[y] for y in sorted(rmap))\n'
        '        new_cols = tuple(cmap[x] for x in sorted(cmap))\n'
        '        return (rows, cols, new_rows, new_cols, sorted(members)), dist\n'
        '\n'
        '\n'
        'def _sgn(v: int) -> int:\n'
        '    return (v > 0) - (v < 0)\n'
        '\n'
        '\n'
        'def _compatible(a, b) -> bool:\n'
        '    """Transfers a=(q, src, dst), b: can one monotone row map x column map carry both?"""\n'
        '    (_, (ax, ay), (atx, aty)), (_, (bx, by), (btx, bty)) = a, b\n'
        '    return _sgn(ax - bx) == _sgn(atx - btx) and _sgn(ay - by) == _sgn(aty - bty)\n'
        '\n'
        '\n'
        'def group_transfers(st: State, transfers: list[tuple[int, Site, Site]]):\n'
        '    """Split transfers into legal moves (largest displacement seeds a group, everything compatible\n'
        '    joins). Returns [(params, dist)] and applies them to st."""\n'
        '    g = st.geo\n'
        '    todo = {q: (q, s, d) for q, s, d in transfers if s != d}\n'
        '    moves = []\n'
        '    guard = 0\n'
        '    while todo:\n'
        '        guard += 1\n'
        '        if guard > 10 * len(transfers) + 50:\n'
        '            raise RuntimeError("grouping did not converge")\n'
        '        movers = set(todo)\n'
        '        # a transfer can go now if its target is free, or held by another mover (who may join)\n'
        '        cands = sorted(todo.values(), key=lambda t: -g.dist(t[1], t[2]))\n'
        '        seed = None\n'
        '        for t in cands:\n'
        '            o = st.occ.get(t[2])\n'
        '            if o is None:\n'
        '                seed = t\n'
        '                break\n'
        '        if seed is None:\n'
        '            # cycle: park one blocker on a free site of its own zone\n'
        '            t = cands[0]\n'
        '            q = st.occ[t[2]]\n'
        '            if q not in todo:\n'
        '                raise RuntimeError("target held by a stationary atom")\n'
        '            free = [s for s in (g.ent_sites if g.in_ent(st.pos[q]) else g.storage_sites) if s not in st.occ]\n'
        '            free.sort(key=lambda s: g.dist(st.pos[q], s))\n'
        '            params, dist = st.apply([(q, free[0])])\n'
        '            moves.append((params, dist))\n'
        '            todo[q] = (q, free[0], todo[q][2])\n'
        '            continue\n'
        '        zs, zt = g.zone_of[seed[1]], g.zone_of[seed[2]]\n'
        '\n'
        '        def fits(t, grp):\n'
        '            return g.zone_of[t[1]] == zs and g.zone_of[t[2]] == zt and all(_compatible(t, u) for u in grp)\n'
        '\n'
        '        group = [seed]\n'
        '        excluded: set[int] = set()\n'
        '        for t in cands:\n'
        '            if t is not seed and fits(t, group):\n'
        '                group.append(t)\n'
        '        sx, sy = seed[1]\n'
        '        while True:\n'
        '            mem = {u[0] for u in group}\n'
        '            xs = [u[1][0] for u in group]\n'
        '            ys = [u[1][1] for u in group]\n'
        '            ghosts = [\n'
        '                st.occ[(x, y)]\n'
        '                for x in range(min(xs), max(xs) + 1)\n'
        '                for y in range(min(ys), max(ys) + 1)\n'
        '                if (x, y) in st.occ and st.occ[(x, y)] not in mem\n'
        '            ]\n'
        '            held = [u for u in group if st.occ.get(u[2]) is not None and st.occ.get(u[2]) not in mem]\n'
        '            if not ghosts and not held:\n'
        '                break\n'
        '            pulled = False\n'
        '            for q in ghosts:\n'
        '                if q in todo and q not in excluded and fits(todo[q], group):\n'
        '                    group.append(todo[q])\n'
        '                    pulled = True\n'
        '            if pulled:\n'
        '                continue\n'
        '            if held:\n'
        '                excluded.update(u[0] for u in held)\n'
        "                group = [u for u in group if u not in held]  # the seed's target is free\n"
        '                continue\n'
        '            if len(group) == 1:\n'
        '                raise RuntimeError("ghost on a single-atom move")\n'
        '            far = max(group[1:], key=lambda u: abs(u[1][0] - sx) + abs(u[1][1] - sy))\n'
        '            excluded.add(far[0])\n'
        '            group.remove(far)\n'
        '        del movers\n'
        '        params, dist = st.apply([(u[0], u[2]) for u in group])\n'
        '        moves.append((params, dist))\n'
        '        for u in group:\n'
        '            del todo[u[0]]\n'
        '    return moves\n'
        '\n'
        '\n'
        '# ---------------------------------------------------------------- the compiler\n'
        '\n'
        '\n'
        'class Compiler:\n'
        '    def __init__(self, circuit: QuantumCircuit, spec: Any, options: dict | None = None):\n'
        '        self.opt = {"cands": 4, "proactive_down": True}\n'
        '        if options:\n'
        '            self.opt.update(options)\n'
        '        self.circuit = circuit\n'
        '        self.geo = Geo(spec)\n'
        '        self.ops, self.n = front_end(circuit)\n'
        '        if self.n > len(self.geo.storage_sites):\n'
        '            raise Unsupported("too many qubits")\n'
        '        self.succ, self.indeg = build_dag(self.ops, self.n)\n'
        '        if len(self.ops) > 150 and not (options and "cands" in options):\n'
        '            self.opt["cands"] = 1  # keep large irregular circuits fast\n'
        '\n'
        '    # ------------------------------------------------------------ setup\n'
        '    def initial_loading(self) -> dict[int, Site]:\n'
        '        g = self.geo\n'
        '        # rows nearest the entangling zone first\n'
        '        rows = sorted(range(g.sy0, g.sy1 + 1), key=lambda y: -y if g.ent_above else y)\n'
        '        sites = [(x, y) for y in rows for x in range(g.sx0, g.sx1 + 1)]\n'
        '        return {q: sites[q] for q in range(self.n)}\n'
        '\n'
        '    # ------------------------------------------------------------ main loop\n'
        '    def run(self):\n'
        '        g = self.geo\n'
        '        n = self.n\n'
        '        ops = self.ops\n'
        '        self.loading = self.initial_loading()\n'
        '        st = State(g, self.loading)\n'
        '        self.st = st\n'
        '        self.out: list[tuple] = []  # ("u", q, name, angle) | ("cz", a, b) | ("move", params) | ("meas", q, c)\n'
        '        self.dist_total = 0.0\n'
        '        U = [I2.copy() for _ in range(n)]\n'
        '        mode = ["idle"] * n  # idle | rot | open\n'
        '        frame: list[str | None] = [None] * n\n'
        '        open_cnt = [0] * n\n'
        '        indeg = list(self.indeg)\n'
        '        bstate: dict[int, str] = {}  # block idx -> "cz1"\n'
        '        brot: dict[int, int] = {}\n'
        '        done = [False] * len(ops)\n'
        '        remaining_cz = [0] * n\n'
        '        for o in ops:\n'
        '            if o.kind in (ROT, CZB):\n'
        '                for q in o.qubits:\n'
        '                    remaining_cz[q] += 2 if o.kind == ROT else 1\n'
        '        ready_blocks: set[int] = set()\n'
        '        pend_meas: list[Op] = []\n'
        '        level = [0] * n  # ASAP depth level per qubit (gates emitted so far)\n'
        '        self.U, self.mode, self.level = U, mode, level\n'
        '\n'
        '        def finish(i):\n'
        '            done[i] = True\n'
        '            for j in self.succ[i]:\n'
        '                indeg[j] -= 1\n'
        '                if indeg[j] == 0:\n'
        '                    ready.append(j)\n'
        '\n'
        '        ready = [o.idx for o in ops if indeg[o.idx] == 0]\n'
        '\n'
        '        def absorb():\n'
        '            # eagerly absorb ready 1q ops / measurements, collect ready blocks\n'
        '            progress = True\n'
        '            while progress:\n'
        '                progress = False\n'
        '                nonlocal ready\n'
        '                rest = []\n'
        '                for i in ready:\n'
        '                    o = ops[i]\n'
        '                    if o.kind == U1:\n'
        '                        q = o.qubits[0]\n'
        '                        if mode[q] == "idle":\n'
        '                            U[q] = o.mat @ U[q]\n'
        '                            finish(i)\n'
        '                            progress = True\n'
        '                        else:\n'
        '                            rest.append(i)\n'
        '                    elif o.kind == MEAS:\n'
        '                        pend_meas.append(o)\n'
        '                        finish(i)\n'
        '                        progress = True\n'
        '                    else:\n'
        '                        ready_blocks.add(i)\n'
        '                ready = [i for i in rest if not done[i]]\n'
        '\n'
        '        absorb()\n'
        '        guard = 0\n'
        '        while ready_blocks or bstate:\n'
        '            guard += 1\n'
        '            if guard > 20 * len(ops) + 100:\n'
        '                raise RuntimeError("scheduler stuck")\n'
        '            events = self._events(ready_blocks, bstate, brot, mode, frame, remaining_cz)\n'
        '            if not events:\n'
        '                raise RuntimeError("no events")\n'
        '            S = self._choose(events, remaining_cz)\n'
        '            # commit: basis changes before CZ1 (they are part of the pending unitary)\n'
        '            for ev in S:\n'
        '                kind, i, r, o_ = ev\n'
        '                op = ops[i]\n'
        '                if kind == "start":\n'
        '                    if op.kind == ROT:\n'
        '                        pr, po = _pauli_on(op, r), _pauli_on(op, o_)\n'
        '                        U[r] = basis_change(pr, "X") @ U[r]\n'
        '                        if mode[o_] != "open":\n'
        '                            U[o_] = basis_change(po, "Z") @ U[o_]\n'
        '                            mode[o_], frame[o_] = "open", po\n'
        '                        open_cnt[o_] += 1\n'
        '                        mode[r] = "rot"\n'
        '                    else:\n'
        '                        for q, w in zip(op.qubits, op.basis):\n'
        '                            U[q] = w @ U[q]\n'
        '            self._route_and_pulse(S, U)\n'
        '            for ev in S:\n'
        '                kind, i, r, o_ = ev\n'
        '                op = ops[i]\n'
        '                for q in op.qubits:\n'
        '                    remaining_cz[q] -= 1\n'
        '                if kind == "start" and op.kind == ROT:\n'
        '                    bstate[i] = "cz1"\n'
        '                    brot[i] = r\n'
        '                    U[r] = _rx(op.theta) @ U[r]\n'
        '                    ready_blocks.discard(i)\n'
        '                elif kind == "finish":\n'
        '                    del bstate[i]\n'
        '                    r = brot.pop(i)\n'
        '                    o_ = [q for q in op.qubits if q != r][0]\n'
        '                    U[r] = basis_change(_pauli_on(op, r), "X").conj().T @ U[r]\n'
        '                    mode[r] = "idle"\n'
        '                    open_cnt[o_] -= 1\n'
        '                    if open_cnt[o_] == 0:\n'
        '                        U[o_] = basis_change(frame[o_], "Z").conj().T @ U[o_]\n'
        '                        mode[o_], frame[o_] = "idle", None\n'
        '                    finish(i)\n'
        '                else:  # single-CZ block\n'
        '                    for q, w in zip(op.qubits, op.basis):\n'
        '                        U[q] = w.conj().T @ U[q]\n'
        '                    ready_blocks.discard(i)\n'
        '                    finish(i)\n'
        '            absorb()\n'
        '        # final: every atom with a pending unitary goes to storage, then measurements\n'
        '        down = [q for q in range(n) if not _is_identity(U[q]) and g.in_ent(st.pos[q])]\n'
        '        self._send_down(down)\n'
        '        for q in range(n):\n'
        '            if not _is_identity(U[q]):\n'
        '                self._flush(q)\n'
        '        for o in sorted(pend_meas, key=lambda o: o.idx):\n'
        '            self.out.append(("meas", o.qubits[0], o.clbit))\n'
        '        return self.out\n'
        '\n'
        '    # ------------------------------------------------------------ scheduling\n'
        '    def _events(self, ready_blocks, bstate, brot, mode, frame, rem):\n'
        '        ops = self.ops\n'
        '        evs = []\n'
        '        for i in bstate:\n'
        '            r = brot[i]\n'
        '            o_ = [q for q in ops[i].qubits if q != r][0]\n'
        '            evs.append(("finish", i, r, o_))\n'
        '        for i in ready_blocks:\n'
        '            op = ops[i]\n'
        '            a, b = op.qubits\n'
        '            if op.kind == CZB:\n'
        '                if mode[a] == "idle" and mode[b] == "idle":\n'
        '                    evs.append(("start", i, None, None))\n'
        '                continue\n'
        '            for r, o_ in ((a, b), (b, a)):\n'
        '                if mode[r] != "idle":\n'
        '                    continue\n'
        '                po = _pauli_on(op, o_)\n'
        '                if mode[o_] == "idle" or (mode[o_] == "open" and frame[o_] == po):\n'
        '                    evs.append(("start", i, r, o_))\n'
        '        # rotator choice: keep only the better orientation per block (rotate the less busy qubit,\n'
        '        # never one that is open)\n'
        '        best: dict[int, tuple] = {}\n'
        '        for ev in evs:\n'
        '            if ev[0] != "start" or ev[2] is None:\n'
        '                continue\n'
        '            k = (self.mode[ev[3]] == "open", rem[ev[3]] - rem[ev[2]])\n'
        '            if ev[1] not in best or k > best[ev[1]][0]:\n'
        '                best[ev[1]] = (k, ev)\n'
        '        return [ev for ev in evs if ev[0] != "start" or ev[2] is None or best[ev[1]][1] is ev]\n'
        '\n'
        '    def _ev_qubits(self, ev):\n'
        '        return self.ops[ev[1]].qubits\n'
        '\n'
        '    def _choose(self, events, rem):\n'
        '        """Greedy matching by priority; a few candidate sets are compared by real routing cost."""\n'
        '        st = self.st\n'
        '        g = self.geo\n'
        '\n'
        '        def est(ev):\n'
        '            a, b = self._ev_qubits(ev)\n'
        '            return g.dist(st.pos[a], st.pos[b])\n'
        '\n'
        '        def prio(ev):\n'
        '            a, b = self._ev_qubits(ev)\n'
        '            return max(rem[a], rem[b])\n'
        '\n'
        '        evs = sorted(events, key=lambda e: (-prio(e), e[0] != "finish", est(e), e[1]))\n'
        '        cands = []\n'
        '        top = evs[: self.opt["cands"]]\n'
        '        for first in top:\n'
        '            used = set(self._ev_qubits(first))\n'
        '            S = [first]\n'
        '            for e in evs:\n'
        '                if e is first:\n'
        '                    continue\n'
        '                qs = self._ev_qubits(e)\n'
        '                if used & set(qs):\n'
        '                    continue\n'
        '                S.append(e)\n'
        '                used.update(qs)\n'
        '            cands.append(S)\n'
        '        if len(cands) == 1:\n'
        '            return cands[0]\n'
        '        best, best_cost = None, None\n'
        '        for S in cands:\n'
        '            cost = self._dry_cost(S)\n'
        '            score = cost / (len(S) + 2.0 * sum(prio(e) for e in S[:1]) / max(1, max(rem)))\n'
        '            if best_cost is None or score < best_cost:\n'
        '                best, best_cost = S, score\n'
        '        return best\n'
        '\n'
        '    def _dry_cost(self, S):\n'
        '        saved = (self.st, self.out, self.dist_total, self.U)\n'
        '        self.st = self.st.copy()\n'
        '        self.out = []\n'
        '        self.dist_total = 0.0\n'
        '        try:\n'
        '            U = [u.copy() for u in self.U]\n'
        '            for kind, i, r, o_ in S:\n'
        '                op = self.ops[i]\n'
        '                if kind == "start" and op.kind == ROT:\n'
        '                    U[r] = basis_change(_pauli_on(op, r), "X") @ U[r]\n'
        '                    if self.mode[o_] != "open":\n'
        '                        U[o_] = basis_change(_pauli_on(op, o_), "Z") @ U[o_]\n'
        '                elif kind == "start":\n'
        '                    for q, w in zip(op.qubits, op.basis):\n'
        '                        U[q] = w @ U[q]\n'
        '            self.U = U\n'
        '            self._route_and_pulse(S, U, dry=True)\n'
        '            return self.dist_total\n'
        '        finally:\n'
        '            self.st, self.out, self.dist_total, self.U = saved[0], saved[1], saved[2], saved[3]\n'
        '\n'
        '    # ------------------------------------------------------------ routing\n'
        '    def _emit_move(self, params, dist):\n'
        '        self.out.append(("move", params))\n'
        '        self.dist_total += dist\n'
        '\n'
        '    def _flush(self, q):\n'
        '        assert self.geo.in_storage(self.st.pos[q])\n'
        '        for name, ang in synth_1q(self.U[q]):\n'
        '            self.out.append(("u", q, name, ang))\n'
        '        self.U[q] = I2.copy()\n'
        '\n'
        '    def _storage_targets(self, qs: list[int], st: State) -> dict[int, Site]:\n'
        '        """Drop zone atoms straight down into the free storage sites nearest the zone, keeping\n'
        '        the order of rows within every column."""\n'
        '        g = self.geo\n'
        '        res: dict[int, Site] = {}\n'
        '        bycol: dict[int, list[int]] = {}\n'
        '        for q in qs:\n'
        '            bycol.setdefault(st.pos[q][0], []).append(q)\n'
        '        taken: set[Site] = set()\n'
        '        for x, group in bycol.items():\n'
        '            group.sort(key=lambda q: st.pos[q][1])\n'
        '            xs = min(max(x, g.sx0), g.sx1)\n'
        '            free = [(xs, y) for y in range(g.sy0, g.sy1 + 1) if (xs, y) not in st.occ and (xs, y) not in taken]\n'
        '            free.sort(key=lambda s: -s[1] if g.ent_above else s[1])\n'
        '            if len(free) >= len(group):\n'
        '                chosen = sorted(free[: len(group)], key=lambda s: s[1])\n'
        '                for q, s in zip(group, chosen):\n'
        '                    res[q] = s\n'
        '                    taken.add(s)\n'
        '            else:\n'
        '                for q in group:\n'
        '                    cand = [s for s in g.storage_sites if s not in st.occ and s not in taken]\n'
        '                    cand.sort(key=lambda s: g.dist(st.pos[q], s))\n'
        '                    res[q] = cand[0]\n'
        '                    taken.add(cand[0])\n'
        '        return res\n'
        '\n'
        '    def _send_down(self, qs):\n'
        '        if not qs:\n'
        '            return\n'
        '        st = self.st\n'
        '        tg = self._storage_targets(qs, st)\n'
        '        for params, dist in group_transfers(st, [(q, st.pos[q], tg[q]) for q in qs]):\n'
        '            self._emit_move(params, dist)\n'
        '\n'
        '    def _route_and_pulse(self, S, U, dry=False):\n'
        '        g = self.geo\n'
        '        st = self.st\n'
        '        ops = self.ops\n'
        '        pairs = [tuple(ops[i].qubits) for _, i, _, _ in S]\n'
        '        in_S = {q for p in pairs for q in p}\n'
        '        # phase A: dirty atoms in the zone go to storage (those in S must; others proactively)\n'
        '        down = []\n'
        '        for q in range(self.n):\n'
        '            if g.in_ent(st.pos[q]) and not _is_identity(U[q]):\n'
        '                if q in in_S or self.opt["proactive_down"]:\n'
        '                    down.append(q)\n'
        '        self._send_down(down)\n'
        '        # phase B: destinations as pair constraints\n'
        '        reserved: set[Site] = set()\n'
        '        tg: dict[int, Site] = {}\n'
        '\n'
        '        def free(s):\n'
        '            return s not in st.occ and s not in reserved\n'
        '\n'
        '        order = sorted(pairs, key=lambda p: -min(self._anchor_cost(p, st)))\n'
        '        for a, b in order:\n'
        '            if g.in_ent(st.pos[a]) and g.sibling.get(st.pos[a]) == st.pos[b]:\n'
        '                continue  # already together\n'
        '            best = None\n'
        '            for anc, mov in ((a, b), (b, a)):\n'
        '                s = st.pos[anc]\n'
        '                if g.in_ent(s) and free(g.sibling[s]):\n'
        '                    c = g.dist(st.pos[mov], g.sibling[s])\n'
        '                    if best is None or c < best[0]:\n'
        '                        best = (c, {mov: g.sibling[s]})\n'
        '            # both move to a free pair\n'
        '            for left, right in g.pairs:\n'
        '                if not (free(left) or st.occ.get(left) in (a, b)) or not (free(right) or st.occ.get(right) in (a, b)):\n'
        '                    continue\n'
        '                if st.occ.get(left) is not None and st.occ.get(left) not in (a, b):\n'
        '                    continue\n'
        '                pa, pb = st.pos[a], st.pos[b]\n'
        '                for qa, qb in ((a, b), (b, a)):\n'
        '                    c = max(g.dist(st.pos[qa], left), g.dist(st.pos[qb], right))\n'
        '                    if best is None or c < best[0] - 1e-9:\n'
        '                        best = (c, {qa: left, qb: right})\n'
        '                del pa, pb\n'
        '            if best is None:\n'
        '                raise RuntimeError("no room in the entangling zone")\n'
        '            for q, s in best[1].items():\n'
        '                tg[q] = s\n'
        '                reserved.add(s)\n'
        '        transfers = [(q, st.pos[q], s) for q, s in tg.items() if st.pos[q] != s]\n'
        '        # atoms leaving storage get their pending 1q gates first\n'
        '        for q, src, _ in transfers:\n'
        '            if g.in_storage(src) and not _is_identity(U[q]):\n'
        '                if not dry:\n'
        '                    self._flush(q)\n'
        '                else:\n'
        '                    U[q] = I2.copy()\n'
        '        for q in in_S:\n'
        '            if not _is_identity(U[q]):\n'
        '                if g.in_storage(st.pos[q]):\n'
        '                    if not dry:\n'
        '                        self._flush(q)\n'
        '                else:\n'
        '                    raise RuntimeError("dirty atom in the zone")\n'
        '        for params, dist in group_transfers(st, transfers):\n'
        '            self._emit_move(params, dist)\n'
        '        # sanity: every pulse pair together, no other pair doubly occupied\n'
        '        if not dry:\n'
        '            for a, b in pairs:\n'
        '                if g.sibling.get(st.pos[a]) != st.pos[b]:\n'
        '                    raise RuntimeError("pair not formed")\n'
        '            for left, right in g.pairs:\n'
        '                qa, qb = st.occ.get(left), st.occ.get(right)\n'
        '                if qa is not None and qb is not None and {qa, qb} not in [set(p) for p in pairs]:\n'
        '                    raise RuntimeError("unwanted pair")\n'
        '            for a, b in pairs:\n'
        '                self.out.append(("cz", a, b))\n'
        '\n'
        '    def _anchor_cost(self, p, st):\n'
        '        g = self.geo\n'
        '        a, b = p\n'
        '        return [g.dist(st.pos[a], st.pos[b])]\n'
        '\n'
        '\n'
        '# ---------------------------------------------------------------- executor (gate-level state machine)\n'
        '\n'
        '\n'
        'class Exec:\n'
        '    """DAG progress plus, per qubit, the pending 1q unitary and the role (idle / rot / open frame).\n'
        '\n'
        '    Events: ("start", block, rotator) and ("finish", block, rotator); rotator is None for single-CZ\n'
        '    blocks. `pre_ws(ev)` = the basis changes an event adds before its CZ (per qubit)."""\n'
        '\n'
        '    def __init__(self, ops, succ, indeg, n):\n'
        '        self.ops, self.succ, self.n = ops, succ, n\n'
        '        self.indeg = list(indeg)\n'
        '        self.U = [I2.copy() for _ in range(n)]\n'
        '        self.mode = ["idle"] * n\n'
        '        self.frame: list[str | None] = [None] * n\n'
        '        self.open_cnt = [0] * n\n'
        '        self.bstate: dict[int, int] = {}\n'
        '        self.done = [False] * len(ops)\n'
        '        self.ready = [o.idx for o in ops if indeg[o.idx] == 0]\n'
        '        self.ready_blocks: set[int] = set()\n'
        '        self.pend_meas: list[Op] = []\n'
        '        self.absorb()\n'
        '\n'
        '    def clone(self) -> "Exec":\n'
        '        e = Exec.__new__(Exec)\n'
        '        e.ops, e.succ, e.n = self.ops, self.succ, self.n\n'
        '        e.indeg = list(self.indeg)\n'
        '        e.U = [u.copy() for u in self.U]\n'
        '        e.mode, e.frame, e.open_cnt = list(self.mode), list(self.frame), list(self.open_cnt)\n'
        '        e.bstate, e.done, e.ready = dict(self.bstate), list(self.done), list(self.ready)\n'
        '        e.ready_blocks, e.pend_meas = set(self.ready_blocks), list(self.pend_meas)\n'
        '        return e\n'
        '\n'
        '    def finished(self) -> bool:\n'
        '        return not self.ready_blocks and not self.bstate\n'
        '\n'
        '    def _finish(self, i):\n'
        '        self.done[i] = True\n'
        '        for j in self.succ[i]:\n'
        '            self.indeg[j] -= 1\n'
        '            if self.indeg[j] == 0:\n'
        '                self.ready.append(j)\n'
        '\n'
        '    def absorb(self):\n'
        '        progress = True\n'
        '        while progress:\n'
        '            progress = False\n'
        '            rest = []\n'
        '            for i in self.ready:\n'
        '                o = self.ops[i]\n'
        '                if o.kind == U1:\n'
        '                    q = o.qubits[0]\n'
        '                    if self.mode[q] == "idle":\n'
        '                        self.U[q] = o.mat @ self.U[q]\n'
        '                        self._finish(i)\n'
        '                        progress = True\n'
        '                    else:\n'
        '                        rest.append(i)\n'
        '                elif o.kind == MEAS:\n'
        '                    self.pend_meas.append(o)\n'
        '                    self._finish(i)\n'
        '                    progress = True\n'
        '                else:\n'
        '                    self.ready_blocks.add(i)\n'
        '            self.ready = [i for i in rest if not self.done[i]]\n'
        '\n'
        '    def other(self, i, r):\n'
        '        return [q for q in self.ops[i].qubits if q != r][0]\n'
        '\n'
        '    def start_roles(self, i) -> list[int | None]:\n'
        '        """Feasible rotators for starting ready block i (None for a single-CZ block)."""\n'
        '        op = self.ops[i]\n'
        '        a, b = op.qubits\n'
        '        if op.kind == CZB:\n'
        '            return [None] if self.mode[a] == "idle" and self.mode[b] == "idle" else []\n'
        '        res = []\n'
        '        for r, o in ((a, b), (b, a)):\n'
        '            if self.mode[r] != "idle":\n'
        '                continue\n'
        '            po = _pauli_on(op, o)\n'
        '            if self.mode[o] == "idle" or (self.mode[o] == "open" and self.frame[o] == po):\n'
        '                res.append(r)\n'
        '        return res\n'
        '\n'
        '    def pre_ws(self, ev) -> dict[int, np.ndarray]:\n'
        '        kind, i, r = ev\n'
        '        op = self.ops[i]\n'
        '        if kind == "finish":\n'
        '            return {}\n'
        '        if op.kind == CZB:\n'
        '            return {q: w for q, w in zip(op.qubits, op.basis)}\n'
        '        o = self.other(i, r)\n'
        '        res = {r: basis_change(_pauli_on(op, r), "X")}\n'
        '        if self.mode[o] != "open":\n'
        '            res[o] = basis_change(_pauli_on(op, o), "Z")\n'
        '        return res\n'
        '\n'
        '    def apply_pre(self, ev, skip=()):\n'
        '        kind, i, r = ev\n'
        '        op = self.ops[i]\n'
        '        for q, w in self.pre_ws(ev).items():\n'
        '            if q not in skip:\n'
        '                self.U[q] = w @ self.U[q]\n'
        '        if kind == "start" and op.kind == ROT:\n'
        '            o = self.other(i, r)\n'
        '            if self.mode[o] != "open":\n'
        '                self.mode[o], self.frame[o] = "open", _pauli_on(op, o)\n'
        '            self.open_cnt[o] += 1\n'
        '            self.mode[r] = "rot"\n'
        '\n'
        '    def apply_post(self, ev):\n'
        '        kind, i, r = ev\n'
        '        op = self.ops[i]\n'
        '        if kind == "start" and op.kind == ROT:\n'
        '            self.bstate[i] = r\n'
        '            self.U[r] = _rx(op.theta) @ self.U[r]\n'
        '            self.ready_blocks.discard(i)\n'
        '        elif kind == "finish":\n'
        '            del self.bstate[i]\n'
        '            o = self.other(i, r)\n'
        '            self.U[r] = basis_change(_pauli_on(op, r), "X").conj().T @ self.U[r]\n'
        '            self.mode[r] = "idle"\n'
        '            self.open_cnt[o] -= 1\n'
        '            if self.open_cnt[o] == 0:\n'
        '                self.U[o] = basis_change(self.frame[o], "Z").conj().T @ self.U[o]\n'
        '                self.mode[o], self.frame[o] = "idle", None\n'
        '            self._finish(i)\n'
        '        else:\n'
        '            for q, w in zip(op.qubits, op.basis):\n'
        '                self.U[q] = w.conj().T @ self.U[q]\n'
        '            self.ready_blocks.discard(i)\n'
        '            self._finish(i)\n'
        '\n'
        '\n'
        'def find_hub(ops: list[Op], n: int) -> int | None:\n'
        '    deg = [set() for _ in range(n)]\n'
        '    for o in ops:\n'
        '        if o.kind in (ROT, CZB):\n'
        '            a, b = o.qubits\n'
        '            deg[a].add(b)\n'
        '            deg[b].add(a)\n'
        '    if n < 4:\n'
        '        return None\n'
        '    h = max(range(n), key=lambda q: (len(deg[q]), q))\n'
        '    return h if len(deg[h]) >= 0.5 * (n - 1) else None\n'
        '\n'
        '\n'
        'class CyclePlanner:\n'
        '    """Hub circuits: the whole register is lifted into the zone, the hub walks over its partners\n'
        '    (one CZ per step), non-hub pairs are formed before the last pulse of a cycle, the register is\n'
        '    dropped back (rotations happen in storage), and the next lift re-forms those pairs for CZ2."""\n'
        '\n'
        '    def __init__(self, geo: Geo, ops, succ, indeg, n, hub, order=None, match="index", hub_min=0.0,\n'
        '                 slack=None, hub_max=1.0, trips=False):\n'
        '        self.geo, self.ops, self.succ, self.indeg, self.n, self.hub = geo, ops, succ, indeg, n, hub\n'
        '        self.match, self.hub_min, self.slack, self.hub_max = match, hub_min, slack, hub_max\n'
        '        self.trips = trips\n'
        '        self.work = 0  # deterministic effort counter (routing evaluations)\n'
        '        # block level in the DAG (1q ops pass levels through): QAOA layer l -> level l\n'
        '        lvl = [0] * len(ops)\n'
        '        for i, o in enumerate(ops):  # edges always point forward in op order\n'
        '            if o.kind in (ROT, CZB):\n'
        '                lvl[i] += 1\n'
        '            for j in succ[i]:\n'
        '                lvl[j] = max(lvl[j], lvl[i])\n'
        '        self.lvl = lvl\n'
        '        g = geo\n'
        '        slots = order if order is not None else self.default_order()\n'
        '        partners = [p for p in slots if p is not None]\n'
        '        m = len(partners)\n'
        '        ncols = (g.ex1 - g.ex0 + 1) // 2\n'
        '        R = max(1, math.ceil(m / ncols))\n'
        '        if len(slots) > R * ncols:\n'
        '            raise Unsupported("order longer than the grid")\n'
        '        if R > g.ey1 - g.ey0 + 1 or R > g.sy1 - g.sy0 + 1 or not g.ent_above:\n'
        '            raise Unsupported("layout does not fit")\n'
        '        self.R = R\n'
        '        self.shift = g.ey0 - (g.sy1 - R + 1)\n'
        '        self.home: dict[int, Site] = {}\n'
        '        for k, p in enumerate(slots):\n'
        '            if p is None:\n'
        '                continue\n'
        '            c, row = divmod(k, R)\n'
        '            self.home[p] = (g.ex0 + 2 * c, g.ey0 + row)\n'
        '        walk = []\n'
        '        for c in range(ncols):\n'
        '            col = [p for p in partners if self.home[p][0] == g.ex0 + 2 * c]\n'
        '            col.sort(key=lambda p: self.home[p][1], reverse=bool(c % 2))\n'
        '            walk += col\n'
        '        self.walk = walk\n'
        '        self.widx = {p: k for k, p in enumerate(walk)}\n'
        '        first = walk[0]\n'
        '        hx, hy = self.home[first]\n'
        '        self.loading = {p: (s[0], s[1] - self.shift) for p, s in self.home.items()}\n'
        '        self.loading[hub] = (hx + 1, hy - self.shift)\n'
        '        self.direction = 1\n'
        '\n'
        '    def default_order(self) -> list[int]:\n'
        '        seen = []\n'
        '        for o in self.ops:\n'
        '            if o.kind in (ROT, CZB) and self.hub in o.qubits:\n'
        '                p = [q for q in o.qubits if q != self.hub][0]\n'
        '                if p not in seen:\n'
        '                    seen.append(p)\n'
        '        seen += [q for q in range(self.n) if q != self.hub and q not in seen]\n'
        '        return seen\n'
        '\n'
        '    # ---------------------------------------------------------- output helpers\n'
        '    def emit_moves(self, transfers):\n'
        '        for params, dist in group_transfers(self.st, transfers):\n'
        '            self.out.append(("move", params))\n'
        '            self.dist_total += dist\n'
        '\n'
        '    def flush(self, q):\n'
        '        for name, ang in synth_1q(self.ex.U[q]):\n'
        '            self.out.append(("u", q, name, ang))\n'
        '        self.ex.U[q] = I2.copy()\n'
        '\n'
        '    # ---------------------------------------------------------- planning one cycle\n'
        '    def direction_of(self, cands) -> bool:\n'
        '        hpos = self.st.pos[self.hub]\n'
        '        a = min(cands, key=lambda p: self.widx[p])\n'
        '        b = max(cands, key=lambda p: self.widx[p])\n'
        '        return self.geo.dist(hpos, self.home[a]) <= self.geo.dist(hpos, self.home[b])\n'
        '\n'
        '    def _allowed(self, ex: Exec, i) -> bool:\n'
        '        if self.slack is None:\n'
        '            return True\n'
        '        low = min((self.lvl[j] for j, o in enumerate(self.ops) if o.kind in (ROT, CZB) and not ex.done[j]\n'
        '                   and j not in ex.bstate), default=0)\n'
        '        return self.lvl[i] <= low + self.slack\n'
        '\n'
        '    def _hub_event(self, ex: Exec, p):\n'
        '        h = self.hub\n'
        '        for i, r in ex.bstate.items():\n'
        '            if r == p and h in self.ops[i].qubits:\n'
        '                return ("finish", i, r)\n'
        '        for i in sorted(ex.ready_blocks):\n'
        '            op = self.ops[i]\n'
        '            if h in op.qubits and p in op.qubits and self._allowed(ex, i):\n'
        '                roles = ex.start_roles(i)\n'
        '                if op.kind == CZB and roles:\n'
        '                    return ("start", i, None)\n'
        '                if p in roles:\n'
        '                    return ("start", i, p)\n'
        '        return None\n'
        '\n'
        '    def _qs(self, ev):\n'
        '        return self.ops[ev[1]].qubits\n'
        '\n'
        '    def _clean_ok(self, ex: Exec, ev, touched) -> bool:\n'
        '        ws = ex.pre_ws(ev)\n'
        '        return all(q not in touched or _is_identity(ws.get(q, I2) @ ex.U[q]) for q in self._qs(ev))\n'
        '\n'
        '    def _commit(self, ex: Exec, pulse, touched):\n'
        '        for ev in pulse:\n'
        '            ex.apply_pre(ev)\n'
        '            for q in self._qs(ev):\n'
        '                if q not in touched:\n'
        '                    ex.U[q] = I2.copy()  # flushed before the lift\n'
        '                    touched.add(q)\n'
        '        for ev in pulse:\n'
        '            ex.apply_post(ev)\n'
        '        ex.absorb()\n'
        '\n'
        '    def plan_cycle(self):\n'
        '        """Pulses of the next cycle, simulated on a copy of the executor: first the CZ2s of the\n'
        '        pairs re-formed by the lift, then one hub event per pulse along the walk, and on the last\n'
        '        pulse a matching of non-hub CZ1s (chosen on the state before that pulse)."""\n'
        '        h = self.hub\n'
        '        self.cycle_trips = None\n'
        '        ex = self.ex.clone()\n'
        '        touched: set[int] = set()\n'
        '        pulses: list[list] = []\n'
        '        p1 = [("finish", i, r) for i, r in sorted(ex.bstate.items()) if h not in self.ops[i].qubits]\n'
        '        if p1:\n'
        '            if not all(self._clean_ok(ex, ev, touched) for ev in p1):\n'
        '                raise RuntimeError("lift pair not clean")\n'
        '            self._commit(ex, p1, touched)\n'
        '            pulses.append(p1)\n'
        '        cands = [p for p in self.walk if self._hub_event(ex, p) is not None]\n'
        '        if cands and self.hub_min > 0 and len(cands) < self.hub_min * len(self.walk):\n'
        '            # few hub events ready: spend this cycle on non-hub work if there is any\n'
        '            if any(h not in self.ops[i].qubits for i in ex.ready_blocks) and not any(\n'
        '                h in self.ops[i].qubits for i in ex.bstate\n'
        '            ):\n'
        '                cands = []\n'
        '        if cands:\n'
        '            hpos = self.st.pos[h]\n'
        '            if self.geo.dist(hpos, self.home[cands[-1]]) < self.geo.dist(hpos, self.home[cands[0]]):\n'
        '                cands.reverse()\n'
        '        snap = None\n'
        '        n_hub = 0\n'
        '        cap = max(1, math.ceil(self.hub_max * len(self.walk)))\n'
        '        # finishes first (they free their partner), then starts, both in walk order\n'
        '        if self.hub_max < 1.0 and cands:\n'
        '            fin = [p for p in cands if self._hub_event(ex, p)[0] == "finish"]\n'
        '            cands = fin + [p for p in cands if p not in fin]\n'
        '            cands = cands[:cap]\n'
        '            sign = 1 if self.direction_of(cands) else -1\n'
        '            cands.sort(key=lambda p: self.widx[p] * sign)\n'
        '        trips: list[set] = [set() for _ in pulses]\n'
        '        if not self.trips:\n'
        '            for p in cands:\n'
        '                ev = self._hub_event(ex, p)\n'
        '                if ev is None or not self._clean_ok(ex, ev, touched):\n'
        '                    continue\n'
        '                snap = (ex.clone(), set(touched), len(pulses))\n'
        '                self._commit(ex, [ev], touched)\n'
        '                pulses.append([ev])\n'
        '                trips.append(set())\n'
        '                n_hub += 1\n'
        '        else:\n'
        '            # dynamic walk: nearest feasible hub event next; a dirty hub may take a storage trip\n'
        '            g = self.geo\n'
        '            hpos = self.st.pos[h]\n'
        '            done_p: set[int] = set()\n'
        '            while n_hub < cap:\n'
        '                best = None\n'
        '                for p in self.walk:\n'
        '                    if p in done_p:\n'
        '                        continue\n'
        '                    ev = self._hub_event(ex, p)\n'
        '                    if ev is None:\n'
        '                        continue\n'
        '                    trip = False\n'
        '                    if not self._clean_ok(ex, ev, touched):\n'
        '                        # only the hub may be dirty, and only if it holds no open block\n'
        '                        ws = ex.pre_ws(ev)\n'
        '                        if not _is_identity(ws.get(p, I2) @ ex.U[p]) and p in touched:\n'
        '                            continue\n'
        '                        if ex.mode[h] == "open" and ev[0] == "start":\n'
        '                            continue\n'
        '                        trip = True\n'
        '                    d = g.dist(hpos, g.sibling[self.home[p]]) + (2.5 if trip else 0.0)\n'
        '                    if best is None or d < best[0]:\n'
        '                        best = (d, p, ev, trip)\n'
        '                if best is None:\n'
        '                    break\n'
        '                _, p, ev, trip = best\n'
        '                snap = (ex.clone(), set(touched), len(pulses))\n'
        '                if trip:\n'
        '                    touched.discard(h)  # flushed during the trip\n'
        '                self._commit(ex, [ev], touched)\n'
        '                pulses.append([ev])\n'
        '                trips.append({h} if trip else set())\n'
        '                done_p.add(p)\n'
        '                hpos = g.sibling[self.home[p]]\n'
        '                n_hub += 1\n'
        '        # matching on the state before the last pulse\n'
        '        if snap is not None:\n'
        '            ex, touched, k = snap[0], snap[1], snap[2]\n'
        '            last = pulses[k]\n'
        '            last_trip = trips[k]\n'
        '            del pulses[k:]\n'
        '            del trips[k:]\n'
        '            if last_trip:\n'
        '                touched.discard(h)\n'
        '        else:\n'
        '            last, last_trip = [], set()\n'
        '        used = {q for ev in last for q in self._qs(ev)}\n'
        '        M = []\n'
        '        # remaining non-hub work per atom: busiest atoms first (greedy edge colouring)\n'
        '        work = [0] * self.n\n'
        '        for i, o in enumerate(self.ops):\n'
        '            if not ex.done[i] and o.kind in (ROT, CZB) and h not in o.qubits:\n'
        '                for q in o.qubits:\n'
        '                    work[q] += 1\n'
        '        if self.match == "work":\n'
        '            mord = sorted(ex.ready_blocks, key=lambda i: (-max(work[q] for q in self.ops[i].qubits),\n'
        '                                                            -min(work[q] for q in self.ops[i].qubits), i))\n'
        '        else:\n'
        '            mord = sorted(ex.ready_blocks)\n'
        '        for i in mord:\n'
        '            op = self.ops[i]\n'
        '            if h in op.qubits or used & set(op.qubits) or not self._allowed(ex, i):\n'
        '                continue\n'
        '            for r in ex.start_roles(i):\n'
        '                ev = ("start", i, r)\n'
        '                if self._clean_ok(ex, ev, touched):\n'
        '                    M.append(ev)\n'
        '                    used.update(op.qubits)\n'
        '                    break\n'
        '        if last or M:\n'
        '            self._commit(ex, last + M, touched)\n'
        '            pulses.append(last + M)\n'
        '            trips.append(last_trip)\n'
        '        self.cycle_trips = trips\n'
        '        return pulses\n'
        '\n'
        '    # ---------------------------------------------------------- execution\n'
        '    def run(self):\n'
        '        g = self.geo\n'
        '        h = self.hub\n'
        '        self.ex = Exec(self.ops, self.succ, self.indeg, self.n)\n'
        '        self.st = State(g, self.loading)\n'
        '        self.out: list[tuple] = []\n'
        '        self.dist_total = 0.0\n'
        '        guard = 0\n'
        '        while not self.ex.finished():\n'
        '            guard += 1\n'
        '            if guard > 4 * len(self.ops) + 20:\n'
        '                raise RuntimeError("cycle planner stuck")\n'
        '            pulses = self.plan_cycle()\n'
        '            if not pulses and self.slack is not None:\n'
        '                keep, self.slack = self.slack, None  # the barrier blocked everything: relax once\n'
        '                pulses = self.plan_cycle()\n'
        '                self.slack = keep\n'
        '            if not pulses:\n'
        '                raise RuntimeError("empty cycle")\n'
        '            # which event touches each qubit first in this cycle\n'
        '            first: dict[int, tuple] = {}\n'
        '            for pl in pulses:\n'
        '                for ev in pl:\n'
        '                    for q in self.ops[ev[1]].qubits:\n'
        '                        first.setdefault(q, ev)\n'
        '            # flush before the lift: pending unitary + basis change of the first event\n'
        '            ex = self.ex\n'
        '            pre_done: dict[int, tuple] = {}\n'
        '            sim = ex.clone()\n'
        '            for pl in pulses:\n'
        '                for ev in pl:\n'
        '                    ws = sim.pre_ws(ev)\n'
        '                    for q in self.ops[ev[1]].qubits:\n'
        '                        if first[q] is ev and q not in pre_done:\n'
        '                            pre_done[q] = (ev, ws.get(q))\n'
        '                    sim.apply_pre(ev)\n'
        '                for ev in pl:\n'
        '                    sim.apply_post(ev)\n'
        '                sim.absorb()\n'
        '            for q, (ev, w) in pre_done.items():\n'
        '                if w is not None:\n'
        '                    ex.U[q] = w @ ex.U[q]\n'
        '                if not g.in_storage(self.st.pos[q]):\n'
        '                    if not _is_identity(ex.U[q]):\n'
        '                        raise RuntimeError("dirty atom outside storage")\n'
        '                    ex.U[q] = I2.copy()\n'
        '                else:\n'
        '                    self.flush(q)\n'
        '            # lift everything that is in storage\n'
        '            self.emit_moves([(q, s, (s[0], s[1] + self.shift)) for q, s in self.st.pos.items() if g.in_storage(s)])\n'
        '            trips = getattr(self, "cycle_trips", None) or [set() for _ in pulses]\n'
        '            for k, pl in enumerate(pulses):\n'
        '                tripped = set()\n'
        '                for q in trips[k] if k < len(trips) else ():\n'
        '                    ev = next(e for e in pl if q in self.ops[e[1]].qubits)\n'
        '                    x, _ = self.st.pos[q]\n'
        '                    xs = min(max(x, g.sx0), g.sx1)\n'
        '                    free = [(xs, y) for y in range(g.sy1, g.sy0 - 1, -1) if (xs, y) not in self.st.occ]\n'
        '                    self.emit_moves([(q, self.st.pos[q], free[0])])\n'
        '                    w = ex.pre_ws(ev).get(q)\n'
        '                    if w is not None:\n'
        '                        ex.U[q] = w @ ex.U[q]\n'
        '                    self.flush(q)\n'
        '                    tripped.add(q)\n'
        '                self.route(pl)\n'
        '                for ev in pl:\n'
        '                    skip = [q for q in self.ops[ev[1]].qubits if first[q] is ev or q in tripped]\n'
        '                    ex.apply_pre(ev, skip=skip)\n'
        '                    for q in self.ops[ev[1]].qubits:\n'
        '                        if not _is_identity(ex.U[q]):\n'
        '                            raise RuntimeError("dirty atom at a pulse")\n'
        '                for ev in pl:\n'
        '                    a, b = self.ops[ev[1]].qubits\n'
        '                    self.out.append(("cz", a, b))\n'
        '                for ev in pl:\n'
        '                    ex.apply_post(ev)\n'
        '                ex.absorb()\n'
        '            # drop everything\n'
        '            self.emit_moves([(q, s, (s[0], s[1] - self.shift)) for q, s in self.st.pos.items() if g.in_ent(s)])\n'
        '        for q in range(self.n):\n'
        '            if not _is_identity(self.ex.U[q]):\n'
        '                if not g.in_storage(self.st.pos[q]):\n'
        '                    raise RuntimeError("final atom outside storage")\n'
        '                self.flush(q)\n'
        '        for o in sorted(self.ex.pend_meas, key=lambda o: o.idx):\n'
        '            self.out.append(("meas", o.qubits[0], o.clbit))\n'
        '        return self.out\n'
        '\n'
        '    def route(self, pulse):\n'
        '        """Moves before a pulse. Each pulse pair is a constraint "a and b on one pair"; for a\n'
        "        non-hub pair either atom may come to the other's sibling site. Atoms that would otherwise\n"
        '        sit in an unwanted pair leave (home if free, else the nearest site that is alone). The\n'
        '        choice per pair is a local search over the real grouped move cost."""\n'
        '        g, st, h = self.geo, self.st, self.hub\n'
        '        pairs = [tuple(self.ops[ev[1]].qubits) for ev in pulse]\n'
        '        decisions = []\n'
        '        for a, b in pairs:\n'
        '            if g.sibling.get(st.pos[a]) == st.pos[b]:\n'
        '                continue\n'
        '            if h in (a, b):\n'
        '                p = b if a == h else a\n'
        '                opt = {h: g.sibling[self.home[p]]}\n'
        '                if st.pos[p] != self.home[p]:\n'
        '                    opt[p] = self.home[p]\n'
        '                decisions.append([opt])\n'
        '                continue\n'
        '            ev = pulse[pairs.index((a, b))]\n'
        '            rot = ev[2] if ev[2] is not None else b\n'
        '            non = a if rot == b else b\n'
        '            hn = self.home[non]\n'
        '            canon = {rot: g.sibling[hn]}\n'
        '            if st.pos[non] != hn:\n'
        '                canon[non] = hn\n'
        '            opts = [canon]\n'
        '            for anchor, mover in ((a, b), (b, a)):\n'
        '                sa = st.pos[anchor]\n'
        '                if g.in_ent(sa):\n'
        '                    o = {mover: g.sibling[sa]}\n'
        '                    if o not in opts:\n'
        '                        opts.append(o)\n'
        '                ha = self.home[anchor]\n'
        '                o = {mover: g.sibling[ha]}\n'
        '                if ha != sa:\n'
        '                    o[anchor] = ha\n'
        '                if o not in opts:\n'
        '                    opts.append(o)\n'
        '            decisions.append(opts)\n'
        '        in_pulse = {q for pr in pairs for q in pr}\n'
        '        best = None\n'
        '        choice = [0] * len(decisions)\n'
        '        cache: dict = {}\n'
        '\n'
        '        def evaluate(ch):\n'
        '            key = tuple(ch)\n'
        '            if key in cache:\n'
        '                return cache[key]\n'
        '            res = self._realize(decisions, ch, pairs, in_pulse)\n'
        '            cache[key] = res\n'
        '            return res\n'
        '\n'
        '        best = evaluate(choice)\n'
        '        for _ in range(2):\n'
        '            improved = False\n'
        '            for k, opts in enumerate(decisions):\n'
        '                for j in range(len(opts)):\n'
        '                    if j == choice[k]:\n'
        '                        continue\n'
        '                    trial = list(choice)\n'
        '                    trial[k] = j\n'
        '                    r = evaluate(trial)\n'
        '                    if r[0] < best[0] - 1e-9:\n'
        '                        best, choice, improved = r, trial, True\n'
        '            if not improved:\n'
        '                break\n'
        '        if best[1] is None:\n'
        '            raise RuntimeError("no legal routing for a pulse")\n'
        '        self.emit_moves(best[1])\n'
        '        for left, right in g.pairs:\n'
        '            qa, qb = st.occ.get(left), st.occ.get(right)\n'
        '            if qa is not None and qb is not None and {qa, qb} not in [set(p) for p in pairs]:\n'
        '                raise RuntimeError("unwanted pair before pulse")\n'
        '        for a, b in pairs:\n'
        '            if g.sibling.get(st.pos[a]) != st.pos[b]:\n'
        '                raise RuntimeError("pair not formed")\n'
        '\n'
        '    def _realize(self, decisions, choice, pairs, in_pulse):\n'
        '        """(cost, transfers) for one choice per decision; cost inf if illegal."""\n'
        '        self.work += 1\n'
        '        g, st, h = self.geo, self.st, self.hub\n'
        '        tg: dict[int, Site] = {}\n'
        '        for opts, c in zip(decisions, choice):\n'
        '            for q, s in opts[c].items():\n'
        '                if q in tg and tg[q] != s:\n'
        '                    return (math.inf, None)\n'
        '                tg[q] = s\n'
        '        final = dict(st.pos)\n'
        '        final.update(tg)\n'
        '        occ: dict[Site, int] = {}\n'
        '        for q in tg:  # movers first: their targets must be distinct\n'
        '            if final[q] in occ:\n'
        '                return (math.inf, None)\n'
        '            occ[final[q]] = q\n'
        '        for q, s in final.items():\n'
        '            if q in tg:\n'
        '                continue\n'
        '            if s in occ:  # a stationary atom sits on a target: it has to leave\n'
        '                if q in in_pulse:\n'
        '                    return (math.inf, None)\n'
        '                final[q] = None\n'
        '                continue\n'
        '            occ[s] = q\n'
        '        pairset = [set(p) for p in pairs]\n'
        '        # atoms displaced by a target, or sitting in an unwanted pair, leave\n'
        '        for _ in range(3 * self.n):\n'
        '            bad = [q for q, s in final.items() if s is None]\n'
        '            for left, right in g.pairs:\n'
        '                qa, qb = occ.get(left), occ.get(right)\n'
        '                if qa is not None and qb is not None and {qa, qb} not in pairset:\n'
        '                    cand = [q for q in (qa, qb) if q not in in_pulse and q not in tg]\n'
        '                    if not cand:\n'
        '                        return (math.inf, None)\n'
        '                    # prefer moving the one away from home (or the hub)\n'
        '                    cand.sort(key=lambda q: (q != h and final[q] == self.home.get(q), q))\n'
        '                    bad.append(cand[0])\n'
        '                    del occ[final[cand[0]]]\n'
        '                    final[cand[0]] = None\n'
        '            if not bad:\n'
        '                break\n'
        '            for q in bad:\n'
        '                if final.get(q) is not None:\n'
        '                    continue\n'
        '                spot = None\n'
        '                hm = self.home.get(q)\n'
        '                if hm is not None and hm not in occ and g.sibling[hm] not in occ:\n'
        '                    spot = hm\n'
        '                else:\n'
        '                    cur = st.pos[q]\n'
        '                    spots = [s for s in g.ent_sites if s not in occ and g.sibling[s] not in occ\n'
        '                             and s[1] < g.ey0 + self.R]\n'
        '                    if not spots:\n'
        '                        return (math.inf, None)\n'
        '                    spot = min(spots, key=lambda s: g.dist(cur, s))\n'
        '                final[q] = spot\n'
        '                occ[spot] = q\n'
        '                tg[q] = spot\n'
        '        transfers = [(q, st.pos[q], s) for q, s in tg.items() if st.pos[q] != s]\n'
        '        try:\n'
        '            moves = group_transfers(st.copy(), transfers)\n'
        '        except RuntimeError:\n'
        '            return (math.inf, None)\n'
        '        return (sum(d for _, d in moves), transfers)\n'
        '\n'
        '    def _target_home(self, q):\n'
        '        return self.home[q] if q != self.hub else self.st.pos[q]\n'
