        '    def from_loading(cls, loading: dict[int, Site], spec: dict | None = None) -> ValidationArchitecture:\n'
        '        """The zones of `spec` (default: the validator\'s) with `loading` (qubit -> `(x, y)`)."""\n'
        '        if not isinstance(loading, dict):\n'
        '            msg = f"The initial loading must be a dict, got {type(loading).__name__}."\n'
        '            raise ArchitectureError(msg)\n'
        '        return cls(*parse_spec(spec), copy.deepcopy(loading))\n'
        '\n'
        '    def reset(self) -> None:\n'
        '        self.positions: dict[int, Site] = dict(self.initial_loading)\n'
        '        self.occupant: dict[Site, int] = {site: qubit for qubit, site in self.positions.items()}\n'
        '\n'
        '    def physical_position(self, site: Site) -> tuple[float, float]:\n'
        '        zone = self.zone_at.get(site)\n'
        '        if zone is None:\n'
        '            msg = f"Site {site} is outside every zone."\n'
        '            raise ArchitectureError(msg)\n'
        '        return physical(zone, site[0], "x"), physical(zone, site[1], "y")\n'
        '\n'
        '    def _pair_spacing(self, sites: Sequence[Site], side: str) -> list[str]:\n'
        '        """Warnings for 3+ lines of a paired axis that mix first and second pair sites."""\n'
        '        found = []\n'
        '        for zone in self.zones.values():\n'
        '            if zone.pair_axis is None:\n'
        '                continue\n'
        '            axis = AXES.index(zone.pair_axis)\n'
        '            lines = sorted({site[axis] for site in sites if zone_contains(zone, site)})\n'
        '            if len(lines) >= 3 and len({pair_slot(zone, line) for line in lines}) > 1:\n'
        '                coords = [round(physical(zone, line, zone.pair_axis), 6) for line in lines]\n'
        '                name = "cols" if zone.pair_axis == "x" else "rows"\n'
        '                found.append(\n'
        '                    f"{side.capitalize()} {name} {tuple(lines)} in the {zone.name!r} zone are not evenly spaced "\n'
        '                    f"physically ({coords}): with 3 or more {name} in a paired zone, use the same site of "\n'
        '                    "every pair (all first or all second sites)."\n'
        '                )\n'
        '        return found\n'
        '\n'
        '    def _check_single_zone(self, sites: dict[int, Site], action: str) -> None:\n'
        '        """Raises if the atoms at `sites` (qubit -> site) are in more than one zone."""\n'
        '        by_zone: dict[str, list[int]] = {}\n'
        '        for qubit, site in sorted(sites.items()):\n'
        '            by_zone.setdefault(self.zone_at[site].name, []).append(qubit)\n'
        '        if len(by_zone) > 1:\n'
        '            where = "; ".join(f"{name!r}: qubits {qubits}" for name, qubits in by_zone.items())\n'
        '            msg = f"Move {action} atoms in more than one zone ({where}); each end of a move must lie in one zone."\n'
        '            raise ArchitectureError(msg)\n'
        '\n'
        '    def apply_move(self, move: ValidatedMove, qubits: Sequence[int]) -> tuple[dict[Site, Site], tuple[str, ...]]:\n'
        '        """Checks `move` on `qubits` against the current state and applies it.\n'
        '\n'
        "        Returns the site mapping and the move's spacing warnings (never errors).\n"
        '        """\n'
        '        if len(qubits) != move.num_qubits or len(set(qubits)) != len(qubits):\n'
        '            msg = f"Move acts on {move.num_qubits} distinct qubits, got {list(qubits)}."\n'
        '            raise ArchitectureError(msg)\n'
        '        spacing = list(move.spacing_warnings)\n'
        '        mapping = site_mapping(move, self.occupant, spacing)\n'
        '        for target in mapping.values():\n'
        '            if target not in self.zone_at:\n'
        '                msg = f"Move target {target} is outside every zone."\n'
        '                raise ArchitectureError(msg)\n'
        '        spacing += self._pair_spacing(list(mapping), "picked-up") + self._pair_spacing(list(mapping.values()), "target")\n'
        '\n'
        '        listed = set(qubits)\n'
        '        picked = {self.occupant[s]: s for s in mapping if s in self.occupant}\n'
        '        if ghost := set(picked) - listed:\n'
        '            qubit = min(ghost)\n'
        '            msg = f"Qubit {qubit} at {picked[qubit]} lies on a selected row/column intersection and would be picked up."\n'
        '            raise ArchitectureError(msg)\n'
        '        if missing := listed - set(picked):\n'
        '            where = {q: self.positions.get(q) for q in sorted(missing)}\n'
        '            msg = f"Qubits {where} are not at any intersection of rows {move.rows} x cols {move.cols}."\n'
        '            raise ArchitectureError(msg)\n'
        '        self._check_single_zone(picked, "picks up")\n'
        '        self._check_single_zone({q: mapping[s] for q, s in picked.items()}, "drops off")\n'
        '        for qubit, source in picked.items():\n'
        '            occupant = self.occupant.get(mapping[source])\n'
        '            if occupant is not None and occupant not in picked:\n'
        '                msg = f"Cannot deposit qubit {qubit} at {mapping[source]}: occupied by qubit {occupant}."\n'
        '                raise ArchitectureError(msg)\n'
        '\n'
        '        for source in picked.values():\n'
        '            del self.occupant[source]\n'
        '        for qubit, source in picked.items():\n'
        '            self.positions[qubit] = mapping[source]\n'
        '            self.occupant[mapping[source]] = qubit\n'
        '        return mapping, tuple(spacing)\n'
        '\n'
        '    def check_gate(self, name: str, qubits: Sequence[int]) -> None:\n'
        '        """Raises unless every qubit is in a zone allowing `name` and a 2-qubit gate acts on a pair."""\n'
        '        if name in ALWAYS_ALLOWED:\n'
        '            return\n'
        '        for qubit in qubits:\n'
        '            site = self.positions[qubit]\n'
        '            zone = self.zone_at.get(site)\n'
        '            if zone is None or name not in zone.operations:\n'
        '                allowed_in = sorted(z.name for z in self.zones.values() if name in z.operations) or "no zone"\n'
        '                where = zone.name if zone else "no zone"\n'
        '                msg = f"{name!r} on qubit {qubit} at {site} ({where}); allowed in: {allowed_in}."\n'
        '                raise ArchitectureError(msg, "zone")\n'
        '        if len(qubits) != 2:\n'
        '            return\n'
        '        a, b = self.positions[qubits[0]], self.positions[qubits[1]]\n'
        '        zone = self.zone_at[a]\n'
        '        if zone.pair_axis is not None and not are_paired(zone, a, b):\n'
        '            msg = (\n'
        '                f"{name!r} needs both atoms on one interaction pair of the {zone.name!r} zone "\n'
        '                f"(sites 2k and 2k+1 along {zone.pair_axis}), but qubit {qubits[0]} is at {a} "\n'
        '                f"and qubit {qubits[1]} at {b}."\n'
        '            )\n'
        '            raise ArchitectureError(msg, "pair")\n'
        '        if zone.pair_axis is None and abs(a[0] - b[0]) + abs(a[1] - b[1]) != 1:\n'
        '            msg = f"{name!r} needs adjacent atoms, but qubit {qubits[0]} is at {a} and qubit {qubits[1]} at {b}."\n'
        '            raise ArchitectureError(msg, "pair")\n'
        '\n'
        '    def run(self, circuit: QuantumCircuit, log_file: str | Path | None = None) -> list[MoveRecord]:\n'
        '        """Replays `circuit` from the initial loading; writes spacing warnings, every violation and the\n'
        '        verdict to `log_file` (default: a new temporary file), kept in `self.log_file` and on a raised error.\n'
        '\n'
