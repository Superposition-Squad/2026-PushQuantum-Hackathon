        '        if log_file is None:\n'
        '            with tempfile.NamedTemporaryFile(prefix="pushquantum_validation_", suffix=".log", delete=False) as tmp:\n'
        '                log_file = tmp.name\n'
        '        self.log_file = Path(log_file)\n'
        '        lines = [f"Replaying {len(circuit.data)} instructions on {circuit.num_qubits} qubits"]\n'
        '        try:\n'
        '            trace, violations = self._replay(circuit, lines)\n'
        '            if violations:\n'
        '                first = violations[0]\n'
        '                more = (\n'
        '                    f" (and {len(violations) - 1} more violation(s), see the replay log)" if len(violations) > 1 else ""\n'
