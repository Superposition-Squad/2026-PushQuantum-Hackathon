        '    cells = [(c, r) for c in range(ncols) for r in range(R)]\n'
        '\n'
        '    def site(cell):\n'
        '        return (geo.ex0 + 2 * cell[0], geo.ey0 + cell[1])\n'
        '\n'
        '    D = {}\n'
        '    for a in cells:\n'
        '        for b in cells:\n'
        '            sa, sb = site(a), site(b)\n'
        '            D[a, b] = min(geo.dist(sa, geo.sibling[sb]), geo.dist(sb, geo.sibling[sa]))\n'
        '    rng = random.Random(seed)\n'
        '    pos = {p: cells[i] for i, p in enumerate(parts)}\n'
        '    occ = {c: p for p, c in pos.items()}\n'
        '    nb: dict[int, list[int]] = {p: [] for p in parts}\n'
        '    for a, b in edges:\n'
        '        nb[a].append(b)\n'
        '        nb[b].append(a)\n'
        '\n'
        '    def local(p):\n'
        '        return sum(D[pos[p], pos[q]] for q in nb[p])\n'
        '\n'
        '    avg_deg = max(1.0, 2 * len(edges) / max(1, len(parts)))\n'
        '    iters = int(min(iters, 160000 / avg_deg, 1000 * len(parts)))\n'
        '    T = 3.0\n'
        '    for _ in range(iters):\n'
        '        a = rng.choice(parts)\n'
        '        cell = rng.choice(cells)\n'
        '        b = occ.get(cell)\n'
        '        if b == a:\n'
        '            continue\n'
        '        old = local(a) + (local(b) if b is not None else 0)\n'
        '        pa = pos[a]\n'
        '        pos[a] = cell\n'
        '        if b is not None:\n'
        '            pos[b] = pa\n'
        '        delta = local(a) + (local(b) if b is not None else 0) - old\n'
        '        if delta <= 0 or rng.random() < math.exp(-delta / T):\n'
        '            occ[cell] = a\n'
        '            if b is not None:\n'
        '                occ[pa] = b\n'
        '            else:\n'
        '                del occ[pa]\n'
        '        else:\n'
        '            pos[a] = pa\n'
        '            if b is not None:\n'
        '                pos[b] = cell\n'
        '        T = max(0.01, T * 0.9998)\n'
        '    order = [None] * len(cells)\n'
        '    for p, c in pos.items():\n'
        '        order[c[0] * R + c[1]] = p\n'
        '    return order  # None marks an empty home cell\n'
        '\n'
