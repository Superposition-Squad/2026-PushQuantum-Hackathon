        'def sa_order(geo: Geo, ops: list[Op], n: int, hub: int, seed: int, iters: int = 40000) -> list[int]:\n'
        '    """Partner order (zone homes column-major) that keeps non-hub neighbours close: simulated\n'
        '    annealing on the summed visitor distance, fixed iteration budget and seed (deterministic)."""\n'
        '    import random\n'
        '\n'
        '    edges = [tuple(o.qubits) for o in ops if o.kind in (ROT, CZB) and hub not in o.qubits]\n'
