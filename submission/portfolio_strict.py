        '            lines.append(f"PASS: {len(trace)} moves replayed, {spacing} spacing warning(s)")\n'
        '            return trace\n'
        '        finally:\n'
        '            self.log_file.write_text("\\n".join(lines) + "\\n", encoding="utf-8")\n'
        '\n'
        '    def _replay(self, circuit: QuantumCircuit, log: list[str]) -> tuple[list[MoveRecord], list[ArchitectureError]]:\n'
        '        if circuit.num_qubits != len(self.initial_loading):\n'
        '            msg = f"Circuit has {circuit.num_qubits} qubits but {len(self.initial_loading)} are loaded."\n'
        '            raise ArchitectureError(msg, "loading")\n'
        '        self.reset()\n'
        '        index_of = {bit: i for i, bit in enumerate(circuit.qubits)}\n'
        '        trace: list[MoveRecord] = []\n'
        '        violations: list[ArchitectureError] = []\n'
        '        step = -1\n'
        '        group: list[AodLines] = []  # moves of the current parallel step\n'
        '        group_qubits: set[int] = set()\n'
        '        group_start: dict[int, Site] = {}  # positions when the step started\n'
        '        layer = _GateLayer()\n'
        '        for index, instruction in enumerate(circuit.data):\n'
        '            operation = instruction.operation\n'
        '            qubits = tuple(index_of[q] for q in instruction.qubits)\n'
        '            if operation.name == MOVE_NAME:\n'
        '                self._close_layer(layer, violations, log)\n'
        '                layer = _GateLayer()\n'
        '            try:\n'
        '                if operation.name != MOVE_NAME:\n'
        '                    group = []\n'
        '                    if len(qubits) == 2:\n'
        '                        layer.add(index, qubits)\n'
        '                    self.check_gate(operation.name, qubits)\n'
        '                    if len(qubits) == 2:\n'
        '                        layer.zones.add(self.zone_at[self.positions[qubits[0]]].name)\n'
        '                    continue\n'
        '                move = ValidatedMove.from_instruction(operation)\n'
        '                before = {q: self.positions[q] for q in qubits}\n'
        '                mapping, spacing = self.apply_move(move, qubits)\n'
        '                after = {q: self.positions[q] for q in qubits}\n'
        '                distance = max(\n'
        '                    math.dist(self.physical_position(before[q]), self.physical_position(after[q])) for q in qubits\n'
        '                )\n'
        '                lines = AodLines.of(mapping)\n'
        '                joins = bool(group) and not group_qubits & set(qubits)\n'
        '                if joins:\n'
        '                    moving = group_qubits | set(qubits)\n'
        '                    stationary = {site for qubit, site in group_start.items() if qubit not in moving}\n'
        '                    joins = all(can_run_in_parallel(lines, other, stationary) for other in group)\n'
        '                if not joins:\n'
        '                    step += 1\n'
        '                    group, group_qubits, group_start = [], set(), {**self.positions, **before}\n'
        '                group.append(lines)\n'
        '                group_qubits.update(qubits)\n'
        '                for message in spacing:\n'
        '                    logger.warning("Instruction %d (move on %s): %s", index, list(qubits), message)\n'
        '                    log.append(f"WARNING: Instruction {index} (move on {list(qubits)}): {message}")\n'
        '                trace.append(MoveRecord(index, move, qubits, after, spacing, distance, step))\n'
        '            except ArchitectureError as error:  # every check runs before any state changes: skip and go on\n'
        '                violation = ArchitectureError(\n'
        '                    f"Instruction {index} ({operation.name} on {list(qubits)}): {error}", error.kind\n'
        '                )\n'
        '                violations.append(violation)\n'
        '                log.append(f"ERROR: {violation}")\n'
        '                group = []\n'
        '        self._close_layer(layer, violations, log)\n'
        '        return trace, violations\n'
        '\n'
        '    def _close_layer(self, layer: _GateLayer, violations: list[ArchitectureError], log: list[str]) -> None:\n'
        '        """Adds an `idle` violation for every zone where the two-qubit gates of `layer` ran while other\n'
        '        atoms sat there: the entangling pulse reaches every atom in the zone, so each must be in a gate."""\n'
        '        for name in sorted(layer.zones):\n'
        '            zone = self.zones[name]\n'
        '            inside = (q for q, site in self.positions.items() if zone_contains(zone, site))\n'
        '            idle = sorted(q for q in inside if q not in layer.qubits)\n'
        '            if not idle:\n'
        '                continue\n'
        '            where = ", ".join(f"{q} at {self.positions[q]}" for q in idle)\n'
        '            span = f"{layer.first}" if layer.first == layer.last else f"{layer.first}-{layer.last}"\n'
        '            violation = ArchitectureError(\n'
        '                f"Instructions {span} (two-qubit gates in the {name!r} zone): qubits {where} sit in that zone "\n'
        '                "without taking part in a two-qubit gate; every atom in the zone must, or be moved out first.",\n'
        '                "idle",\n'
        '            )\n'
        '            violations.append(violation)\n'
        '            log.append(f"ERROR: {violation}")\n'
        '\n'
        '\n'
        '@dataclass\n'
        'class _GateLayer:\n'
        '    """The two-qubit gates between two moves: the atoms stand still, so they share entangling pulses."""\n'
        '\n'
        '    first: int = -1\n'
        '    last: int = -1\n'
        '    qubits: set[int] = field(default_factory=set)\n'
        '    zones: set[str] = field(default_factory=set)\n'
        '    """Zones where a legal two-qubit gate of the layer ran."""\n'
        '\n'
        '    def add(self, index: int, qubits: Sequence[int]) -> None:\n'
        '        if self.first < 0:\n'
        '            self.first = index\n'
        '        self.last = index\n'
        '        self.qubits.update(qubits)\n'
